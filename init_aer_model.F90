MODULE M_INIT_AER_MODEL

    CONTAINS

    SUBROUTINE INIT_AER_MODEL(YPAER_ACLIB, &
        & KIDIA, KFDIA, KLON, KLEV, KLUOUT, &
        & YAEROUT_ACLIB)

        USE PARKIND1, ONLY : JPIM, JPRB
        USE YOMHOOK,    ONLY  : LHOOK, DR_HOOK  
        USE MODD_PARAM_AER_ACLIB, ONLY : TPARAM_AER_ACLIB, TAEROUT_ACLIB
        USE M_MOCAGE_AERO_INI, ONLY : MOCAGE_AERO_INI
        
        IMPLICIT NONE

        ! -- ARGUMENTS
        TYPE(TPARAM_AER_ACLIB),        INTENT(IN)    :: YPAER_ACLIB
        INTEGER(KIND=JPIM),            INTENT(IN)    :: KIDIA, KFDIA
        INTEGER(KIND=JPIM),            INTENT(IN)    :: KLON, KLEV
        INTEGER(KIND=JPIM),            INTENT(IN)    :: KLUOUT
        TYPE(TAEROUT_ACLIB), OPTIONAL, INTENT(INOUT) :: YAEROUT_ACLIB

        ! -- Local variables
        INTEGER(KIND=JPIM) :: JAER
        REAL(KIND=JPRB)    :: ZHOOK_HANDLE

        !-- CHECK RELIABILITY OF INPUT ARGUMENTS.

!------------------------------------------------------------------------------
IF (LHOOK) CALL DR_HOOK('M_INIT_AER_MODEL:INIT_AER_MODEL',0,ZHOOK_HANDLE)
!------------------------------------------------------------------------------

!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
! Initialization of structure containing aerosol diagnostics !!
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
! Specific initialization for each model !!
!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

        SELECT CASE (TRIM(YPAER_ACLIB%CAERO_HOSTMODEL)) 

            CASE ('MOCAGE')
                ! Initialization of variables for MOCAGE in the YAEROUT structure
               
                CALL MOCAGE_AERO_INI(KLUOUT)


            CASE ('tactic')

                ! Initialization of variables for TACTIC in the YAEROUT structure
                ALLOCATE(YAEROUT_ACLIB%PLOAD(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PEMIS(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PDRYDEP(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PSEDIM(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEP(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEPBCR(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEPBCS(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEPINR(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEPINS(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEPRER(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PWETDEPRES(KLON,YPAER_ACLIB%NAERO))
                ALLOCATE(YAEROUT_ACLIB%PAERAODS   (KLON,YPAER_ACLIB%NAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PAERAAODS  (KLON,YPAER_ACLIB%NAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PAERACAODS (KLON,YPAER_ACLIB%NAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PAEREXTS   (KLON,KLEV,YPAER_ACLIB%NAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PAERSCATS  (KLON,KLEV,YPAER_ACLIB%NAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTYPAODS   (KLON,YPAER_ACLIB%NTYPAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTYPAAODS  (KLON,YPAER_ACLIB%NTYPAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTYPACAODS (KLON,YPAER_ACLIB%NTYPAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTYPEXTS   (KLON,KLEV,YPAER_ACLIB%NTYPAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTYPSCATS  (KLON,KLEV,YPAER_ACLIB%NTYPAERO,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTAODS   (KLON,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTAODLT1S (KLON,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTAAODS  (KLON,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTACAODS (KLON,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTEXTS   (KLON,KLEV,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTSCATS  (KLON,KLEV,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTSSAS   (KLON,YPAER_ACLIB%NSW))   
                ALLOCATE(YAEROUT_ACLIB%PTOTASYS   (KLON,YPAER_ACLIB%NSW))   

                ALLOCATE(YAEROUT_ACLIB%PTAUAER    (KLON,KLEV,YPAER_ACLIB%NSW))
                ALLOCATE(YAEROUT_ACLIB%POMGAER    (KLON,KLEV,YPAER_ACLIB%NSW))
                ALLOCATE(YAEROUT_ACLIB%PASYAER    (KLON,KLEV,YPAER_ACLIB%NSW))
                ALLOCATE(YAEROUT_ACLIB%PTAUAERL   (KLON,KLEV,YPAER_ACLIB%NLW))
                ALLOCATE(YAEROUT_ACLIB%POMGAERL   (KLON,KLEV,YPAER_ACLIB%NLW))
                ALLOCATE(YAEROUT_ACLIB%PASYAERL   (KLON,KLEV,YPAER_ACLIB%NLW))
                ALLOCATE(YAEROUT_ACLIB%PMAERIND   (KLON,KLEV,3))
                DO JAER = 1,YPAER_ACLIB%NAERO
                    YAEROUT_ACLIB%PEMIS(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PDRYDEP(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PSEDIM(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEP(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEPBCR(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEPBCS(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEPINR(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEPINS(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEPRER(KIDIA:KFDIA,JAER) = 0.0_JPRB
                    YAEROUT_ACLIB%PWETDEPRES(KIDIA:KFDIA,JAER) = 0.0_JPRB
                ENDDO


            CASE ('MESONH')
                WRITE(KLUOUT,*) 'INITIALIZATION FOR ', &
                    & TRIM(YPAER_ACLIB%CAERO_HOSTMODEL),' aerosols still to be implemented'

  
            CASE DEFAULT
                WRITE(KLUOUT,*) 'INITIALIZATION FOR ', &
                    & TRIM(YPAER_ACLIB%CAERO_HOSTMODEL),' aerosols still to be implemented'
        END SELECT


!------------------------------------------------------------------------------
IF (LHOOK) CALL DR_HOOK('M_INIT_AER_MODEL:INIT_AER_MODEL',1,ZHOOK_HANDLE)
!------------------------------------------------------------------------------
    END SUBROUTINE INIT_AER_MODEL

END MODULE M_INIT_AER_MODEL
