SUBROUTINE APL_AROME_INIT(YDCST, YDMODEL, YDCPG_BNDS, YDCPG_OPTS, YDCPG_GPAR, &
                        & YDMF_PHYS_BASE_STATE, &
                        & LDMSE, LDSFORCS, &
                        & PQDM, PRHODREFM, PRHODJM, PEXNREFM, PPABSM, &
                        & PUM, PVM, PWM, PUS, PVS, PWS, &
                        & PTKEM, PPTKEM, PTKES, &
                        & PZZ, PRM, PTHM, PTHS, &
                        & PTHVREFM, PRS, &
                        & PACPRR, PACPRS, PACPRG, &
                        & PINPRR_NOTINCR, PINPRS_NOTINCR, PINPRG_NOTINCR, &
                        & PSVM, PSVS, PLIMAM, PLIMAS, PAEROM, PAEROS)

!**** *APL_AROME_INIT* - Setup and change arome variables

!     Author.
!     -------
!      Rolf Heilemann Myhre *Met Norway*
!      Original : 01-09-2023
!      See APL_AROME for modification history

!-----------------------------------------------------------------------

! -   INPUT ARGUMENTS.
!     -------------------
!
!   YDCST:                Model constants
!   YDMODEL:              Model configuration settings
!   YDCPG_BNDS:           Array dimensions and bounds
!   YDCPG_OPTS:           Various dimensions
!   YDCPG_GPAR:
!   YDMF_PHYS_BASE_STATE:
!
!   PRM:   Moist variables at time t
!   PTKEM: Turbulent kinetic energy
!   PSVM:  Passive scalars
!   PSVS:  Passive scalars
!   PUM:   Zonal wind
!   PVM:   Meridian wind
!   PWM:   Vertical velocity (m/s)
!

  USE PARKIND1, ONLY: JPRB, JPIM

  USE YOMCST,                      ONLY: TCST
  USE TYPE_MODEL,                  ONLY: MODEL
  USE CPG_OPTS_TYPE_MOD,           ONLY: CPG_BNDS_TYPE, CPG_OPTS_TYPE
  USE CPG_TYPE_MOD,                ONLY: CPG_GPAR_TYPE

  USE MF_PHYS_BASE_STATE_TYPE_MOD, ONLY: MF_PHYS_BASE_STATE_TYPE

  USE YOMHOOK,                     ONLY: LHOOK, DR_HOOK, JPHOOK

  IMPLICIT NONE

  TYPE(TCST),                    INTENT(IN) :: YDCST
  TYPE(MODEL),                   INTENT(IN) :: YDMODEL
  TYPE(CPG_BNDS_TYPE),           INTENT(IN) :: YDCPG_BNDS
  TYPE(CPG_OPTS_TYPE),           INTENT(IN) :: YDCPG_OPTS
  TYPE(CPG_GPAR_TYPE),           INTENT(IN) :: YDCPG_GPAR

  TYPE(MF_PHYS_BASE_STATE_TYPE), INTENT(IN) :: YDMF_PHYS_BASE_STATE

  LOGICAL, INTENT(IN) :: LDMSE
  LOGICAL, INTENT(IN) :: LDSFORCS

  REAL(KIND=JPRB), INTENT(OUT) :: PQDM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(OUT) :: PRHODREFM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PRHODJM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PEXNREFM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(OUT) :: PPABSM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)

  REAL(KIND=JPRB), INTENT(OUT) :: PUM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PVM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PWM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PUS(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PVS(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PWS(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)

  REAL(KIND=JPRB), INTENT(OUT) :: PTKEM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(OUT) :: PPTKEM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PTKES(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB), INTENT(OUT) :: PZZ(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(OUT) :: PRM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_PHY_MF%YRPARAR%NRR)
  REAL(KIND=JPRB), INTENT(OUT) :: PTHM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(OUT) :: PTHS(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)

  REAL(KIND=JPRB), INTENT(OUT) :: PTHVREFM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)  ! thetav de l etat
  REAL(KIND=JPRB), INTENT(OUT) :: PRS(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_PHY_MF%YRPARAR%NRR)

  REAL(KIND=JPRB), INTENT(OUT) :: PACPRR(YDCPG_BNDS%KFDIA)
  REAL(KIND=JPRB), INTENT(OUT) :: PACPRS(YDCPG_BNDS%KFDIA)
  REAL(KIND=JPRB), INTENT(OUT) :: PACPRG(YDCPG_BNDS%KFDIA)

  REAL(KIND=JPRB), INTENT(OUT) :: PINPRR_NOTINCR(YDCPG_BNDS%KFDIA)
  REAL(KIND=JPRB), INTENT(OUT) :: PINPRS_NOTINCR(YDCPG_BNDS%KFDIA)
  REAL(KIND=JPRB), INTENT(OUT) :: PINPRG_NOTINCR(YDCPG_BNDS%KFDIA)

  REAL(KIND=JPRB), INTENT(OUT) :: PSVM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NGFL_EXT)
  REAL(KIND=JPRB), INTENT(OUT) :: PSVS(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NGFL_EXT)
  REAL(KIND=JPRB), INTENT(OUT) :: PLIMAM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NLIMA)
  REAL(KIND=JPRB), INTENT(OUT) :: PLIMAS(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NLIMA)
  REAL(KIND=JPRB), INTENT(OUT) :: PAEROM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NAERO)
  REAL(KIND=JPRB), INTENT(OUT) :: PAEROS(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NAERO)

  REAL(KIND=JPRB) :: ZRSCP
  REAL(KIND=JPRB) :: ZINVATM
  REAL(KIND=JPRB) :: ZRHO
  REAL(KIND=JPRB) :: ZINVG
  REAL(KIND=JPRB) :: ZINVDT

  REAL(KIND=JPRB), PARAMETER :: PPTKEMIN = 1.E-6

  INTEGER(KIND=JPIM) :: JLON
  INTEGER(KIND=JPIM) :: JLEV
  INTEGER(KIND=JPIM) :: JRR
  INTEGER(KIND=JPIM) :: JGFL

  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

  !------------------------------------------------------------------


  !------------------------------------------------------------------

  IF (LHOOK) CALL DR_HOOK('APL_AROME_INIT_MOD:APL_AROME_INIT', 0, ZHOOK_HANDLE)

  ZINVG=1._JPRB/YDCST%RG
  ZRSCP=YDCST%RD/YDCST%RCPD
  ZINVATM=1/YDCST%RATM
  ZINVDT=1/YDCPG_OPTS%ZDTPHY

  ! adhoc solution to avoid negative tke values
  DO JLEV=1, YDCPG_OPTS%KFLEVG
    DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
      PTKEM(JLON,JLEV) = MAX(YDMF_PHYS_BASE_STATE%TKE(JLON,JLEV), PPTKEMIN)
    ENDDO
  ENDDO

  !initialisation de PZZ
  !initialisation de qdm (utile localement pour calculer rho
  !et convertir q en r
  IF (YDMODEL%YRML_PHY_MF%YRPARAR%NRR == 7) THEN
    DO JLEV = 1,YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        PQDM(JLON,JLEV) = 1._JPRB &
                      & - YDMF_PHYS_BASE_STATE%Q(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%L(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%R(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%I(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%S(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%G(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%H(JLON,JLEV)
      ENDDO
    ENDDO
  ELSE
    DO JLEV = 1,YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
        PQDM(JLON,JLEV) = 1._JPRB &
                      & - YDMF_PHYS_BASE_STATE%Q(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%L(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%R(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%I(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%S(JLON,JLEV) &
                      & - YDMF_PHYS_BASE_STATE%G(JLON,JLEV)
      ENDDO
    ENDDO
  ENDIF

  DO JLEV = 1,YDCPG_OPTS%KFLEVG
    DO JLON = YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA

      !initialisation de PRHODREFM (=qd*zrho)
      ZRHO = YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(JLON,JLEV)  &
         & /(YDMF_PHYS_BASE_STATE%YCPG_DYN%RCP%R(JLON,JLEV) &
         & * YDMF_PHYS_BASE_STATE%T(JLON,JLEV))
      PRHODREFM(JLON,JLEV) = ZRHO*PQDM(JLON,JLEV)
      PRHODJM(JLON,JLEV) = YDMF_PHYS_BASE_STATE%YCPG_PHY%XYB%DELP(JLON,JLEV)*ZINVG

      !initialisation de PEXNREFM
      PEXNREFM(JLON,JLEV) = (YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(JLON,JLEV)*ZINVATM)**(ZRSCP)

      ! vent horizontal et TKE
      PPABSM(JLON,JLEV) = YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(JLON,JLEV)
      PUM(JLON,JLEV) = YDMF_PHYS_BASE_STATE%U(JLON,JLEV)
      PVM(JLON,JLEV) = YDMF_PHYS_BASE_STATE%V(JLON,JLEV)
      PWM(JLON,JLEV) = YDMF_PHYS_BASE_STATE%YCPG_PHY%W(JLON,JLEV)
      PPTKEM(JLON,JLEV) = PTKEM(JLON,JLEV)
      PZZ(JLON,JLEV) = YDMF_PHYS_BASE_STATE%YCPG_DYN%PHI(JLON,JLEV)*ZINVG

    ENDDO
  ENDDO

  !initialisation de PRM pour les hydrometeores (ri=qi/qd)
  DO JLEV = 1, YDCPG_OPTS%KFLEVG
    DO JLON = YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      PTHM(JLON,JLEV)  = YDMF_PHYS_BASE_STATE%T(JLON,JLEV)/PEXNREFM(JLON,JLEV)
      PRM(JLON,JLEV,1) = YDMF_PHYS_BASE_STATE%Q(JLON,JLEV)/PQDM(JLON,JLEV)
      PRM(JLON,JLEV,2) = YDMF_PHYS_BASE_STATE%L(JLON,JLEV)/PQDM(JLON,JLEV)
      PRM(JLON,JLEV,3) = YDMF_PHYS_BASE_STATE%R(JLON,JLEV)/PQDM(JLON,JLEV)
      PRM(JLON,JLEV,4) = YDMF_PHYS_BASE_STATE%I(JLON,JLEV)/PQDM(JLON,JLEV)
      PRM(JLON,JLEV,5) = YDMF_PHYS_BASE_STATE%S(JLON,JLEV)/PQDM(JLON,JLEV)
      PRM(JLON,JLEV,6) = YDMF_PHYS_BASE_STATE%G(JLON,JLEV)/PQDM(JLON,JLEV)
    ENDDO
  ENDDO

  IF (YDMODEL%YRML_PHY_MF%YRPARAR%NRR == 7) THEN
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        PRM(JLON,JLEV,7) = YDMF_PHYS_BASE_STATE%H(JLON,JLEV)/PQDM(JLON,JLEV)
      ENDDO
    ENDDO
  ENDIF

  IF (YDMODEL%YRML_PHY_MF%YRPARAR%NRR == 6) THEN

    !initialisation de PTHVREFM
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        PTHVREFM(JLON,JLEV) = PTHM(JLON,JLEV)* &
         & (1._JPRB + PRM(JLON,JLEV,1)*(YDCST%RV/YDCST%RD))/ &
         & (1._JPRB + PRM(JLON,JLEV,1) + PRM(JLON,JLEV,2) &
         &          + PRM(JLON,JLEV,3) + PRM(JLON,JLEV,4) &
         &          + PRM(JLON,JLEV,5) + PRM(JLON,JLEV,6))
      ENDDO
    ENDDO

  ELSEIF (YDMODEL%YRML_PHY_MF%YRPARAR%NRR == 7) THEN

    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        PTHVREFM(JLON,JLEV) = PTHM(JLON,JLEV)* &
         & (1._JPRB + PRM(JLON,JLEV,1)*(YDCST%RV/YDCST%RD))/ &
         & (1._JPRB + PRM(JLON,JLEV,1) + PRM(JLON,JLEV,2) &
         &          + PRM(JLON,JLEV,3) + PRM(JLON,JLEV,4) &
         &          + PRM(JLON,JLEV,5) + PRM(JLON,JLEV,6) &
         &          + PRM(JLON,JLEV,7))
      ENDDO
    ENDDO

  ENDIF

  !!! initialisation des variables d etat MNH a t+dt
  !!! division pas le pas de temps
  !!!(la multiplication par rhodj est faite plus tard, si necessaire,
  !!! suivant les parametrisations)

  ! initialise pointers :
  ! vent horizontal
  DO JLEV = 1, YDCPG_OPTS%KFLEVG
    DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
      PUS(JLON,JLEV)   = YDMF_PHYS_BASE_STATE%U(JLON,JLEV)*ZINVDT
      PVS(JLON,JLEV)   = YDMF_PHYS_BASE_STATE%V(JLON,JLEV)*ZINVDT
      PWS(JLON,JLEV)   = YDMF_PHYS_BASE_STATE%YCPG_PHY%W(JLON,JLEV)*ZINVDT
      PTKES(JLON,JLEV) = PTKEM(JLON,JLEV)*ZINVDT
      PTHS(JLON,JLEV)  = PTHM(JLON,JLEV)*ZINVDT
    ENDDO
  ENDDO

  !initialisation de PRS pour les hydrometeores
  DO JRR=1,YDMODEL%YRML_PHY_MF%YRPARAR%NRR
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
        PRS(JLON,JLEV,JRR) = PRM(JLON,JLEV,JRR)*ZINVDT
      ENDDO
    ENDDO
  ENDDO

  !initialisation des tableaux de precipitations inst. and cumulated
  !and surface fluxes for turbulence
  IF (LDMSE .OR. LDSFORCS) THEN
    PACPRR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA) = YDCPG_GPAR%ACPRR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    PACPRS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA) = YDCPG_GPAR%ACPRS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    PACPRG(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA) = YDCPG_GPAR%ACPRG(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    PINPRR_NOTINCR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA) = YDCPG_GPAR%INPRR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    PINPRS_NOTINCR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA) = YDCPG_GPAR%INPRS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    PINPRG_NOTINCR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA) = YDCPG_GPAR%INPRG(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
  ENDIF

  !initialisation des scalaires passifs
  DO JGFL=1,YDMODEL%YRML_GCONF%YGFL%NGFL_EXT
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
        PSVM(JLON,JLEV,JGFL) = YDMF_PHYS_BASE_STATE%P1EXT(JLON,JLEV,JGFL)
        PSVS(JLON,JLEV,JGFL) = YDMF_PHYS_BASE_STATE%P1EXT(JLON,JLEV,JGFL)*ZINVDT
      ENDDO
    ENDDO
  ENDDO

  !initialisation des concentrations LIMA
  DO JGFL=1,YDMODEL%YRML_GCONF%YGFL%NLIMA
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
        PLIMAM(JLON,JLEV,JGFL) = YDMF_PHYS_BASE_STATE%P1LIMA(JLON,JLEV,JGFL)
        PLIMAS(JLON,JLEV,JGFL) = YDMF_PHYS_BASE_STATE%P1LIMA(JLON,JLEV,JGFL)*ZINVDT
      ENDDO
    ENDDO
  ENDDO

  ! NRT AEROSOL 
  IF (YDMODEL%YRML_GCONF%YGFL%NAERO /= 0) THEN
    DO JGFL= 1, YDMODEL%YRML_GCONF%YGFL%NAERO
      DO JLEV = 1, YDCPG_OPTS%KFLEVG
        DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
          PAEROM(JLON,JLEV,JGFL) = MAX(YDMF_PHYS_BASE_STATE%P1AERO(JLON,JLEV,JGFL),0._JPRB)
          PAEROS(JLON,JLEV,JGFL) = MAX(YDMF_PHYS_BASE_STATE%P1AERO(JLON,JLEV,JGFL),0._JPRB)*ZINVDT
        END DO
      ENDDO
    ENDDO
  ENDIF

  IF (LHOOK) CALL DR_HOOK('APL_AROME_INIT_MOD:APL_AROME_INIT', 1, ZHOOK_HANDLE)

END SUBROUTINE APL_AROME_INIT
