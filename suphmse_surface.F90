SUBROUTINE SUPHMSE_SURFACE(YDGEOMETRY, YDMODEL, KULOUT, CDCONFSFX, KPROMA)

!**** *SUPHMSE*   - Initialize SURFEX

!     Purpose.
!     --------
!           Initialize MODD_PARAMETERS, MODD_CST, MODD_CONF,
!           MODD_RAIN_ICE_DESCR, MODD_RAIN_ICE_PARAM, MODD_BUDGET
!           parameters used in meso_NH Physics and aladin/meso_NH physics
!           interface

!**   Interface.
!     ----------
!        *CALL* *SUPHMSE_SURFACE(KULOUT)

!        Explicit arguments :
!        --------------------
!        KULOUT : Logical unit for the output

!        Implicit arguments :
!        --------------------
!        COMMON YOMPHY2

!     Method.
!     -------
!        See documentation

!     Externals.
!     ----------

!     Reference.
!     ----------
!        Documentation AROME

!     Author.
!     -------
!        R. Zaaboul

!     Modifications.
!     --------------
!        Original : 21-Oct-2011  (part of suphmse.F90)
!        G.Mozdzynski     2011 : OOPS cleaning, use of derived type TGSGEOM
!        A. Mary : April 2012 : add CLPGD_FNAME
!        P. Marguinaud : Sep 2012 : Cleaning + move CALL SUGRIDSFX here
!        O. Marsden: June 2015 CY42 YRGMV, YRGFL, YRSURF, YRGMV5, and YRGFL5 are now passed by argument
!        P. Marguinaud : Jun 2018; read restart files
!        R. El Khatib 08-Jul-2022 Contribution to the encapsulation of YOMCST and YOETHF
!        2022-08-25 J.M. Piriou: for some variables, double precision JPRD required for simple precision runs.
!        M. Michou Jun 2023 Modifications to consider aerosol and/or chemical gazeous species of ARPEGE-Climat
!     ------------------------------------------------------------------

USE YOMIOS, ONLY : CFRCF

USE GEOMETRY_MOD , ONLY : GEOMETRY
USE PARKIND1  ,ONLY : JPIM     ,JPRB    ,JPRD 
USE YOMHOOK   ,ONLY : LHOOK,   DR_HOOK, JPHOOK

USE TYPE_MODEL, ONLY : MODEL
USE YOMLUN    ,ONLY : NULOUT, NULNAM
USE YOMCST    ,ONLY : YDCST=>YRCST ! allows use of included functions. REK.
USE YOMGPPB   ,ONLY : GPARBUF
USE YOMRIP0   ,ONLY : NINDAT, NSSSSS, RTIMST, LASTRF
USE YOMCT0    ,ONLY : LELAM
USE YOM_YGFL  ,ONLY : YGFL
USE YOMQNSE, ONLY : RQNSE_S0, RQNSE_GU1, RQNSE_GU2, RQNSE_GS1, RQNSE_GS2, RQNSE_GS3, RQNSE_GS4
USE YOMMP0 , ONLY : NPROC, MYPROC, MY_REGION_NS, MY_REGION_EW
USE MODD_IO_SURF_ARO, ONLY : SURFEX_FIELD_BUF_DEALLOC, &
                           & YSURFEX_CACHE_IN_IO_SURF, &
                           & YSURFEX_CACHE_IN
USE MODD_SURF_ATM_TURB_n 
#ifdef CPLOASIS
USE MODD_SFX_OASIS,      ONLY : LOASIS
USE MODI_SFX_OASIS_DEFINE
USE MODD_SURFEX_ARO, ONLY : YSURFEX_ARO_CUR
#endif

!     ------------------------------------------------------------------

IMPLICIT NONE

TYPE (GEOMETRY),        INTENT (IN)    :: YDGEOMETRY
TYPE (MODEL),TARGET,    INTENT (INOUT) :: YDMODEL
INTEGER (KIND=JPIM),    INTENT (IN)    :: KULOUT
CHARACTER (LEN=*),      INTENT (IN)    :: CDCONFSFX
INTEGER (KIND=JPIM),    INTENT (IN)    :: KPROMA
#ifdef CPLOASIS
INTEGER(KIND=JPIM), ALLOCATABLE  :: IGPARAL(:)
INTEGER(KIND=JPIM), ALLOCATABLE  :: IGLOBAL(:,:)
INTEGER :: I,IGL,JL,JGL
INTEGER :: ISEG
#endif

#include "abor1.intfb.h"
#include "posnam.intfb.h"

#include "fctast.func.h"
#include "fcttim.func.h"
#include "aroini_mnhc.h"
#include "aroini_nsv.h"

#include "aroini_surfa.h"
#include "sugridsfx.h"
#include "aroini_surfb.h"
#include "aroini_surfc.h"
#include "reresf_sfx.h"

LOGICAL , POINTER ::  LFTZERO
LOGICAL , POINTER ::  LPGDFWR
INTEGER(KIND=JPIM) , POINTER ::  NSURFEXCTL
INTEGER(KIND=JPIM) , POINTER ::  NSTEP_DUMP_STATE(:)
LOGICAL , POINTER ::  LHISFWR
REAL (KIND=JPRB) , POINTER ::  XZSEPS

#include "namphmse.nam.h"

REAL(KIND=JPRB) :: ZCO2

! Double precision JPRD required for simple precision runs.
REAL(KIND=JPRD) :: ZTI, ZTETA

REAL(KIND=JPRB), DIMENSION (:,:),ALLOCATABLE :: ZGPAR
REAL(KIND=JPRB), DIMENSION (:,:),ALLOCATABLE :: ZGPAR2
REAL(KIND=JPRB), DIMENSION (:),  ALLOCATABLE :: ZMU0
INTEGER(KIND=JPIM) :: IENDC,JKGLO,JF,JLON
INTEGER(KIND=JPIM) :: IDAY, IMONTH, IYEAR, IMYPROC, IA0,IM0,IJ0,IS0, ISSADD
LOGICAL :: LLPAR

INTEGER(KIND=JPIM) :: IVAR, ZNVAR
INTEGER(KIND=JPIM) :: IFILE
TYPE(SURF_ATM_TURB_t) :: YLSURF_ATM_TURB
LOGICAL               :: LLRESTART
LOGICAL               :: LLCHEM_ARPC, LLAERO_ARPC, LLCHEMAERO_ARPC

REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

IF (LHOOK) CALL DR_HOOK('SUPHMSE_SURFACE',0,ZHOOK_HANDLE)
ASSOCIATE(YDDIM=>YDGEOMETRY%YRDIM,YDDIMV=>YDGEOMETRY%YRDIMV,YDGEM=>YDGEOMETRY%YRGEM, YDMP=>YDGEOMETRY%YRMP, &
 & YRGSGEOM_NB=>YDGEOMETRY%YRGSGEOM_NB, YDRIP=>YDMODEL%YRML_GCONF%YRRIP, YDML_LBC=>YDMODEL%YRML_LBC, &
 & YDPARAR=>YDMODEL%YRML_PHY_MF%YRPARAR, YDMCC=>YDMODEL%YRML_AOC%YRMCC, &
 & YDDYNA=>YDMODEL%YRML_DYN%YRDYNA, &
 & YRPHY=>YDMODEL%YRML_PHY_MF%YRPHY, YRPHY0=>YDMODEL%YRML_PHY_MF%YRPHY0, YRLOUIS=>YDMODEL%YRML_PHY_MF%YRLOUIS)
ASSOCIATE(NSWB_MNH=>YDPARAR%NSWB_MNH, MVTS=>YDPARAR%MVTS, &
 & MALBSCA=>YDPARAR%MALBSCA, MALBDIR=>YDPARAR%MALBDIR, MVEMIS=>YDPARAR%MVEMIS, &
 & NGPAR=>YDPARAR%NGPAR, NSV=>YDPARAR%NSV, MLSM=>YDPARAR%MLSM, &
 & NSURFEXCTLMAX=>YDMODEL%YRML_PHY_MF%YRMSE%NSURFEXCTLMAX, CPREFIX_SFX1=>YDMODEL%YRML_PHY_MF%YRMSE%CPREFIX_SFX1, &
 & TSTEP=>YDRIP%TSTEP, &
 & NGPTOTG=>YDGEM%NGPTOTG, NGPTOT_CAP=>YDGEM%NGPTOT_CAP, NGPTOT=>YDGEM%NGPTOT, &
 & NSTA=>YDMP%NSTA , NONL=>YDMP%NONL, NPTRFRSTLAT=>YDMP%NPTRFRSTLAT, &
 & NFRSTLAT=>YDMP%NFRSTLAT, NLSTLAT=>YDMP%NLSTLAT, NLOENG=>YDGEM%NLOENG, &
 & NGFL_EXT=>YGFL%NGFL_EXT, RSOVR=>YDRIP%RSOVR, RSIDEC=>YDRIP%RSIDEC, &
 & RCODEC=>YDRIP%RCODEC, RHGMT=>YDRIP%RHGMT, LACLIB=>YDMODEL%YRML_PHY_MF%YRPHY%LACLIB, &
 & RDECLI=>YDRIP%RDECLI, REQTIM=>YDRIP%REQTIM, RSIVSR=>YDRIP%RSIVSR, &
 & RCOVSR=>YDRIP%RCOVSR, RWSOVR=>YDRIP%RWSOVR, &
 & LMCC03=>YDMCC%LMCC03, LRDUST=>YDMODEL%YRML_PHY_MF%YRARPHY%LRDUST,&
 & LTWOTL=>YDDYNA%LTWOTL, &
 & LCOEFKTKE=>YRPHY%LCOEFKTKE, LCOEFK_F1=>YRPHY%LCOEFK_F1, CGTURS=>YRPHY%CGTURS, &
 & NUPTKE=>YRPHY0%NUPTKE, C3TKEFREE=>YRPHY0%C3TKEFREE, ETKE_OLAM=>YRPHY0%ETKE_OLAM, EFB_UR=>YRPHY0%EFB_UR, &
 & EFB_AZ0=>YRPHY0%EFB_AZ0, REFB_1=>YRPHY0%REFB_1, REFB_2=>YRPHY0%REFB_2, REFB_3=>YRPHY0% REFB_3, &
 & RMD=>YDCST%RMD, RDAY=>YDCST%RDAY, REA=>YDCST%REA, REPSM=>YDCST%REPSM, RPI=>YDCST%RPI, &
 & RLOUIS_S0=>YRLOUIS%RLOUIS_S0, PLOUIS_S0=>YRLOUIS%PLOUIS_S0, RLOUIS_GU1=>YRLOUIS%RLOUIS_GU1, &
 & RLOUIS_GU2=>YRLOUIS%RLOUIS_GU2, PLOUIS_GU1=>YRLOUIS%PLOUIS_GU1, PLOUIS_GU2=>YRLOUIS%PLOUIS_GU2, &
 & RLOUIS_GS1=>YRLOUIS%RLOUIS_GS1, RLOUIS_GS2=>YRLOUIS%RLOUIS_GS2, RLOUIS_GS3=>YRLOUIS%RLOUIS_GS3, & 
 & RLOUIS_GS4=>YRLOUIS%RLOUIS_GS4, PLOUIS_GS1=>YRLOUIS%PLOUIS_GS1, PLOUIS_GS2=>YRLOUIS%PLOUIS_GS2, &
 & PLOUIS_GS3=>YRLOUIS%PLOUIS_GS3, PLOUIS_GS4=>YRLOUIS%PLOUIS_GS4, LCHEM_ARPCLIM=>YDMODEL%YRML_CHEM%YRCHEM%LCHEM_ARPCLIM, NCHEM=>YDMODEL%YRML_GCONF%YGFL%NCHEM,CHEM_SCHEME=>YDMODEL%YRML_CHEM%YRCHEM%CHEM_SCHEME, & 
 & AERO_SCHEME=>YDMODEL%YRML_CHEM%YRCOMPO%AERO_SCHEME,NAERO=>YDMODEL%YRML_GCONF%YGFL%NAERO)

LPGDFWR => YDMODEL%YRML_PHY_MF%YRMSE%LPGDFWR
NSURFEXCTL => YDMODEL%YRML_PHY_MF%YRMSE%NSURFEXCTL
NSTEP_DUMP_STATE => YDMODEL%YRML_PHY_MF%YRMSE%NSTEP_DUMP_STATE
LFTZERO => YDMODEL%YRML_PHY_MF%YRMSE%LFTZERO
LHISFWR => YDMODEL%YRML_PHY_MF%YRMSE%LHISFWR
XZSEPS => YDMODEL%YRML_PHY_MF%YRMSE%XZSEPS

CALL POSNAM(NULNAM,'NAMPHMSE')
READ(NULNAM,NAMPHMSE)

WRITE(NULOUT,*) ' LPGDFWR = ', LPGDFWR, ' LHISFWR = ', LHISFWR, ' LFTZERO = ', LFTZERO
WRITE(UNIT=NULOUT,FMT='('' NSTEP_DUMP_STATE = '',24I5)') NSTEP_DUMP_STATE

! ANNEE

IYEAR = NINDAT / 10000
! MOIS

IMONTH = (NINDAT - 10000*IYEAR ) / 100
! JOUR DU MOIS

IDAY = NINDAT - 10000*IYEAR - 100*IMONTH

IMYPROC=MYPROC

! initialisation of turbulence parameters
CALL SURF_ATM_TURB_SET(YLSURF_ATM_TURB, &
 & LCOEFKTKE, LCOEFK_F1, CGTURS, &
 & REAL(NUPTKE), C3TKEFREE, ETKE_OLAM, EFB_UR, EFB_AZ0, REFB_1, REFB_2, REFB_3, &
 & RQNSE_S0, RQNSE_GU1, RQNSE_GU2, RQNSE_GS1, RQNSE_GS2, RQNSE_GS3, RQNSE_GS4, &
 & RLOUIS_S0, PLOUIS_S0, RLOUIS_GU1, RLOUIS_GU2, PLOUIS_GU1, PLOUIS_GU2, &
 & RLOUIS_GS1, RLOUIS_GS2, RLOUIS_GS3, RLOUIS_GS4, &
 & PLOUIS_GS1, PLOUIS_GS2, PLOUIS_GS3, PLOUIS_GS4)

!     Initialisation of surface scheme
! for surface
LLAERO_ARPC     = .FALSE.
LLCHEM_ARPC     = .FALSE.
LLCHEMAERO_ARPC = .FALSE.
LLAERO_ARPC     = AERO_SCHEME == "tactic" .AND. NAERO>0
LLCHEM_ARPC     = LCHEM_ARPCLIM.AND.(TRIM(CHEM_SCHEME).EQ.'arpclim_relacs'.OR.TRIM(CHEM_SCHEME).EQ.'mocage')
LLCHEMAERO_ARPC = LLAERO_ARPC.AND.LLCHEM_ARPC

IF (LLCHEMAERO_ARPC) THEN
    NSV=NAERO+NCHEM
ELSE IF (LLCHEM_ARPC) THEN
    NSV=NCHEM
ELSE IF (LLAERO_ARPC) THEN
    NSV=NAERO
  ELSE IF (LACLIB .AND. LRDUST) THEN
    NSV=NAERO
 ELSE
    NSV=NGFL_EXT
 ENDIF
!initialisation de ZCO2 pour la surface (Il sera écrasé ensuite sous suecrad/surdi)
ZCO2=360.E-06_JPRB*44.0/RMD

IF (ALLOCATED (YDPARAR%XSW_BANDS)) DEALLOCATE (YDPARAR%XSW_BANDS)
ALLOCATE (YDPARAR%XSW_BANDS(NSWB_MNH))

!  DO J=1,NSWB_MNH
!    XSW_BANDS(J)=((RLIMIT(J)+RLIMIT(J+1))/2.)*10E-6
!  ENDDO
!On initialise en dur pour l'instant xsw_bands, mais il serait mieux de le
!faire dans le setup du rayonnement (suswn)

SELECT CASE (NSWB_MNH)
  CASE (1)
    YDPARAR%XSW_BANDS(1)=999.
  CASE (2)
    YDPARAR%XSW_BANDS(1)=0.47_JPRB
    YDPARAR%XSW_BANDS(2)=2.345_JPRB
    YDPARAR%XSW_BANDS=YDPARAR%XSW_BANDS*0.000001_JPRB
  CASE (4)
    YDPARAR%XSW_BANDS(1)=0.47_JPRB
    YDPARAR%XSW_BANDS(2)=0.94_JPRB
    YDPARAR%XSW_BANDS(3)=1.785_JPRB
    YDPARAR%XSW_BANDS(4)=3.19_JPRB
    YDPARAR%XSW_BANDS=YDPARAR%XSW_BANDS*0.000001_JPRB
  CASE (6)
    YDPARAR%XSW_BANDS(1)=0.215_JPRB
    YDPARAR%XSW_BANDS(2)=0.345_JPRB
    YDPARAR%XSW_BANDS(3)=0.565_JPRB
    YDPARAR%XSW_BANDS(4)=0.94_JPRB
    YDPARAR%XSW_BANDS(5)=1.785_JPRB
    YDPARAR%XSW_BANDS(6)=3.19_JPRB
    YDPARAR%XSW_BANDS=YDPARAR%XSW_BANDS*0.000001_JPRB
  CASE DEFAULT
    CALL ABOR1('SUPHMSE_SURFACE: NSWB_MNH /= 1,2,4,6 not coded')
ENDSELECT

! calculation of astronomical parameters needed by ini_surf
! as it is done in updtim.f90
ALLOCATE (ZMU0(NGPTOT))

RHGMT=REAL(MOD(NSSSSS,NINT(RDAY)),JPRB)
IF (LTWOTL) THEN
  ISSADD=NINT(TSTEP*0.5_JPRB)
ELSE
  ISSADD=0_JPIM
ENDIF
IF (LASTRF) THEN
  IJ0=NDD(NINDAT)
  IM0=NMM(NINDAT)
  IA0=NCCAA(NINDAT)
  ! Keep a year close to year 2000 (reference year)
  ! so that RET is correctly used
  IA0 = MOD(IA0,4)+2000
  IS0 = INT(RHGMT)
  ZTI=RTIME(IA0,IM0,IJ0,IS0,RDAY)+ISSADD
  ZTETA=RTETA(ZTI)
ELSE
  ZTI=RTIMST+ISSADD
  ZTETA =RTETA(ZTI)
ENDIF
RDECLI=RDS(ZTETA)
REQTIM=RET(ZTETA)
RSOVR =REQTIM+RHGMT
RWSOVR=RSOVR*2.0_JPRB*RPI/RDAY
RCODEC=COS(RDECLI)
RSIDEC=SIN(RDECLI)
RCOVSR=COS(RWSOVR)
RSIVSR=SIN(RWSOVR)
DO JKGLO=1,NGPTOT
  ZMU0(JKGLO)=MAX ( RSIDEC*YRGSGEOM_NB%GEMU(JKGLO)&
  & -RCODEC*RCOVSR*SQRT(1.0_JPRB-YRGSGEOM_NB%GEMU(JKGLO)**2)*COS(YRGSGEOM_NB%GELAM(JKGLO))&
  & +RCODEC*RSIVSR*SQRT(1.0_JPRB-YRGSGEOM_NB%GEMU(JKGLO)**2)*SIN(YRGSGEOM_NB%GELAM(JKGLO))&
  & ,0.0_JPRB )
ENDDO

! allocation du buffer
ALLOCATE (ZGPAR(NGPTOT,NGPAR))
ALLOCATE (ZGPAR2(KPROMA,NGPAR))

LLPAR = NGPAR /= 0

IF (LLPAR) THEN
   ZGPAR=0.0_JPRB
   ZGPAR2=0.0_JPRB
ENDIF

IF (NSURFEXCTL > 0) THEN

  YSURFEX_CACHE_IN => YSURFEX_CACHE_IN_IO_SURF
  
  ! Initialization of how many times we should do initialization
  IVAR=1
  INIT: DO
  
    IF (CDCONFSFX >= 'A') THEN
      CALL AROINI_SURFA (KULOUT, NGPTOT, NGPTOT_CAP, KPROMA, NPROC, IMYPROC, NGPTOTG, PTSTEP=TSTEP, KNVAR=ZNVAR)
    ENDIF
  
    IF (CDCONFSFX >= 'B') THEN
      
      IF ((IVAR > 1) .AND. (IVAR < ZNVAR)) THEN

        IFILE=90+IVAR-2
        CALL SUGRIDSFX (YSURFEX_CACHE_IN, YDGEOMETRY, YDRIP, YDMODEL%YRML_PHY_MF%YRMSE, KFILE=IFILE)

      ELSE

        INQUIRE (FILE=CFRCF, EXIST=LLRESTART)

        IF (LLRESTART) THEN
          CALL RERESF_SFX (YSURFEX_CACHE_IN, YDGEOMETRY, YDMODEL)
          CALL AROINI_SURFB                               ! Don't check date
        ELSE
          CALL SUGRIDSFX (YSURFEX_CACHE_IN, YDGEOMETRY, YDRIP, YDMODEL%YRML_PHY_MF%YRMSE)
          CALL AROINI_SURFB (IYEAR, IMONTH, IDAY, NSSSSS) ! Check date
        ENDIF

      ENDIF

    ENDIF
  
    IF (CDCONFSFX >= 'C') THEN
      CALL AROINI_SURFC (NSV, NSWB_MNH, ZCO2, ZMU0, ZGPAR(:,MALBDIR:MALBDIR+NSWB_MNH-1), ZGPAR(:,MALBSCA:MALBSCA+NSWB_MNH-1),    &
                       & ZGPAR(:,MVEMIS), ZGPAR(:,MVTS), YDPARAR%XSW_BANDS, LMCC03, ZGPAR(:,MLSM), YLSURF_ATM_TURB, LLPAR)
      CALL SURFEX_FIELD_BUF_DEALLOC (YSURFEX_CACHE_IN_IO_SURF)
    ENDIF
  
    ! Check if we need more initalizations
    IF (IVAR == ZNVAR) THEN
      EXIT INIT
    ELSE
      ! It this is not the last time we do initialization, release surfex memory
      ! so we can start a new initialization for a new file
      CALL DEALLMSE
      IVAR=IVAR+1
    ENDIF
  ENDDO INIT

#ifdef CPLOASIS
!----------------------------------------------------------------------------
IF (LOASIS) THEN
!
! Define parallelisation scheme for oasis
!
  WRITE(KULOUT,'(A)')'Setting up OASIS3 partition information'
!
  ! Set arguments for an OASIS3 orange partition
  ALLOCATE(IGPARAL(2*(NLSTLAT(MY_REGION_NS)-NFRSTLAT(MY_REGION_NS)+1)+2))
  IGPARAL(1)=3
  IGPARAL(2)=NLSTLAT(MY_REGION_NS)-NFRSTLAT(MY_REGION_NS)+1
!!CLB: segments number could be overestimated this way in AROME/ALADIN
!
  ! Construct a global grid point number arrays
  ALLOCATE(IGLOBAL(YDGEOMETRY%YRDIM%NDLON,YDGEOMETRY%YRDIM%NDGLG))
  I=0
  IGLOBAL(:,:)=0
  DO JGL=1,YDGEOMETRY%YRDIM%NDGLG
     DO JL=1,NLOENG(JGL)
        I=I+1
        IGLOBAL(JL,JGL) = I
     ENDDO
  ENDDO
!
  ! Compute global offsets and local extents (based on sump.F90 code).
!
!CLB
  WRITE(KULOUT,'(A)')'OASIS3 orange partition information'
  WRITE(KULOUT,*)MY_REGION_EW,MY_REGION_NS,&
    &NFRSTLAT(MY_REGION_NS),NLSTLAT(MY_REGION_NS)
  I=2
  DO JGL=NFRSTLAT(MY_REGION_NS),NLSTLAT(MY_REGION_NS)
     IGL=NPTRFRSTLAT(MY_REGION_NS)+JGL-NFRSTLAT(MY_REGION_NS)
!
     IF(NSTA(IGL,MY_REGION_EW)<1) THEN
       IGPARAL(2)=IGPARAL(2)-1
     ELSE
!
     I=I+1
     IGPARAL(I)=IGLOBAL(NSTA(IGL,MY_REGION_EW),JGL)-1
     I=I+1
     IGPARAL(I)=NONL(IGL,MY_REGION_EW)
     WRITE(KULOUT,*) JGL,IGL,NSTA(IGL,MY_REGION_EW),NONL(IGL,MY_REGION_EW)
!
     ENDIF
!
  ENDDO
!
!  WRITE(KULOUT,'(A)')'OASIS3 orange partition information'
  WRITE(KULOUT,'(3A14)')'Segment','Global offset','Local extent'
!
  ISEG=IGPARAL(2)
  DO I=1,ISEG
!  DO I=1,IGPARAL(2)
     WRITE(KULOUT,'(3I14)')I,IGPARAL(2*I+1),IGPARAL(2*I+2)
  ENDDO
  DEALLOCATE(IGLOBAL)
!
  CALL SFX_OASIS_DEFINE(YSURFEX_ARO_CUR%IM%O,YSURFEX_ARO_CUR%U,'AROME', &
 &                      NGPTOT,IGPARAL(1:2*ISEG+2))
!
ENDIF
!----------------------------------------------------------------------------
#endif

ENDIF

IF (LLPAR .AND. .NOT. LLRESTART) THEN

! When we restart, GPARBUF is read from restart file

  DO JKGLO=1,NGPTOT,KPROMA
    IENDC=MIN(KPROMA,NGPTOT-JKGLO+1)
 
    DO JF=1,NGPAR
      DO JLON=1,IENDC
        ZGPAR2(JLON,JF)=ZGPAR(JKGLO+JLON-1,JF)
      ENDDO
    ENDDO
 
    GPARBUF (:, :, 1+(JKGLO-1)/YDGEOMETRY%YRDIM%NPROMA) = ZGPAR2
    
  ENDDO

ENDIF

DEALLOCATE (ZMU0)
DEALLOCATE (ZGPAR)
DEALLOCATE (ZGPAR2)


END ASSOCIATE
END ASSOCIATE
IF (LHOOK) CALL DR_HOOK('SUPHMSE_SURFACE',1,ZHOOK_HANDLE)

END SUBROUTINE SUPHMSE_SURFACE

