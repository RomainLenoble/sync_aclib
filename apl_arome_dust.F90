SUBROUTINE APL_AROME_DUST(YDCST, YDMODEL, YDCPG_BNDS, YDCPG_OPTS, & 
                        & YDMF_PHYS_BASE_STATE, &
                        & YDMF_PHYS_SURF, &
                        & YDMF_PHYS, &
                        & YDCPG_MISC, &
                        & YDVARS, &
                        & YDCPG_DYN0, &
                        & KIOFF_MFSHAL, &
                        & PZZ, PDZZ, PPABSM, PRHM, PDT, PFPR, PNEBMNH, &
                        & PTHM, PRHODREFM, PAEROMIN, &
                        & PCHEM2AER, PTENCHEM2AER, &
                        & YLAEROUT_ACLIB,&
                        & PAERD, PTENDAERO, &
                        & PAEROM, PP1EZDIAG, &
                        & PPIZA_DST, PCGA_DST, PTAUREL_DST)

!**** *APL_AROME_DUST* - Setup and call Arome dust

!     Author.
!     -------
!      Rolf Heilemann Myhre *Met Norway*
!      Original : 01-09-2023
!      See APL_AROME for modification history
!
!      03-2025 S. Antoine & Y. Seity : Adpation to ACLIB library
!      07-2025 S. Antoine & Y. Seity : Replace GFL EXT by GFL AERO
!      03-2025 R. Lenoble : Add ACLIB library and tactic scheme for aerosols
!-----------------------------------------------------------------------

! -   INPUT ARGUMENTS.
!     -------------------
!
!   YDCST:                Model constants
!   YDMODEL:              Model configuration settings
!   YDCPG_BNDS:           Array dimensions and bounds
!   YDCPG_OPTS:           Various dimensions
!   YDMF_PHYS_BASE_STATE: Base state variables (thermodynamic fields)
!   YDMF_PHYS_SURF:       Surface physics variables
!   YDMF_PHYS:            Physics fields
!   YDCPG_DYN0:           Dynamic fields
!   YDCPG_MISC:           Diagnostic variables (for nebulosity) ?
!   YDVARS:               Persistent fields
!   KIOFF_MFSHAL:         Offset for first useful field (EZDIAG use in Chemistry/Dust), (=3)
!   PZZ:                  [m] Height of layers
!   PDZZ:                 [m] Layer thickness
!   PPABSM:                FULL-LEVEL PRESSURE
!   PRHM:                 [kg/m3] Air volumic mass
!   PDT:                  [s] Time step
!   PTHM:                 [K] Potential temperature
!   PRHODREFM:            [kg/m3] Density of air (reference state)
!   PAEROMIN:             [moments/molec_air] Transported moments of dust/aerosols
!
! -   INPUT/OUTPUT ARGUMENTS.
!     -------------------------
!
!   PCHEM2AER:            [mol/mol] Chemical concentrations to be used for aerosol formation
!   PTENCHEM2AER:         [mol/mol/s] Chemical tendencies updated from aerosol formation
!   PAERD:                Extinction coefficient at 550 nm for dust layers (LRDUST)
!   PTENDAERO:            [units/s] Passive scalars tendency (AEROSOL TENDENCY)
!   PP1EZDIAG:            Diag Nb/m3,ug/m3,rg(nb;um),rg(m;um),SSA,assym,AOD/550,mode & wvl (LRDUST)
!
! -   OUTPUT ARGUMENTS.
!     ------------------
!
!   PAEROM:               [units] Passive scalars (AEROSOL CONCENTRATION)
!   PPIZA_DST:            Single scattering albedo of dust (points, lev, wvl) (LRDUST)
!   PCGA_DST:             Asymmetry factor for dust (points, lev, wvl) (LRDUST)
!   PTAUREL_DST:          [tau/tau_550] Optical depth ratio for dust layers (points, lev, wvl) (LRDUST)

  USE PARKIND1, ONLY: JPRB, JPIM

  USE YOMCST,                        ONLY: TCST
  USE TYPE_MODEL,                    ONLY: MODEL
  USE CPG_OPTS_TYPE_MOD,             ONLY: CPG_BNDS_TYPE, CPG_OPTS_TYPE
  USE MF_PHYS_BASE_STATE_TYPE_MOD,   ONLY: MF_PHYS_BASE_STATE_TYPE
  USE CPG_TYPE_MOD,                  ONLY: CPG_DYN_TYPE, CPG_MISC_TYPE
  USE MODD_NSV,                      ONLY: NSV_DSTBEG, NSV_DSTEND
  USE MODD_CST_ACLIB,                ONLY: YDCST_ACLIB
  USE MODD_ACLIB_n,                  ONLY: YPAER_ACLIB, YAEROSOLS, YAEROUT_ACLIB
  USE MF_PHYS_SURFACE_TYPE_MOD,      ONLY: MF_PHYS_SURF_TYPE
  USE MODD_ACLIB_N,                  ONLY: YPCHEM_ACLIB, YCHEMS
  USE FIELD_VARIABLES_MOD,           ONLY: FIELD_VARIABLES
  USE MODD_PARAM_CHEM_ACLIB,         ONLY : TPARAM_CHEM_ACLIB
  USE MF_PHYS_TYPE_MOD,              ONLY: MF_PHYS_TYPE
  USE YOMLUN,                        ONLY : NULOUT
  USE MODD_PARAM_AER_ACLIB,          ONLY : TAEROUT_ACLIB
  USE M_INIT_AER_MODEL,              ONLY : INIT_AER_MODEL
  USE MODD_SURFEX_ARO, ONLY : YSURFEX_ARO_CUR, YSURFEX_ARO_ALL
  USE MODD_FROMMPA,      ONLY : CPROGRAM_MSE
  USE MODI_GET_SURF_VAR_N

  USE YOMHOOK,                  ONLY: LHOOK, DR_HOOK, JPHOOK

  IMPLICIT NONE

  TYPE(TCST),                    INTENT(IN)    :: YDCST
  TYPE(MODEL),                   INTENT(IN)    :: YDMODEL
  TYPE(CPG_BNDS_TYPE),           INTENT(IN)    :: YDCPG_BNDS
  TYPE(CPG_OPTS_TYPE),           INTENT(IN)    :: YDCPG_OPTS
  TYPE(MF_PHYS_BASE_STATE_TYPE), INTENT(IN)    :: YDMF_PHYS_BASE_STATE
  TYPE(MF_PHYS_SURF_TYPE),       INTENT(IN)    :: YDMF_PHYS_SURF
  TYPE(CPG_DYN_TYPE),            INTENT(IN)    :: YDCPG_DYN0
  TYPE(CPG_MISC_TYPE),           INTENT(IN)    :: YDCPG_MISC
  TYPE(FIELD_VARIABLES),         INTENT(IN)    :: YDVARS
  TYPE(MF_PHYS_TYPE),            INTENT(IN)    :: YDMF_PHYS

  INTEGER(KIND=JPIM), INTENT(IN) :: KIOFF_MFSHAL

  REAL(KIND=JPRB), INTENT(IN)    :: PZZ(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PDZZ(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PPABSM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(IN)    :: PRHM(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PDT
  REAL(KIND=JPRB), INTENT(IN)    :: PFPR(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_PHY_MF%YRPARAR%NRR)
  REAL(KIND=JPRB), INTENT(IN)    :: PNEBMNH(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB), INTENT(IN)    :: PTHM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(IN)    :: PRHODREFM(YDCPG_BNDS%KFDIA, 0:YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB), INTENT(IN)    :: PAEROMIN(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NAERO)

  REAL(KIND=JPRB),INTENT(INOUT)  :: PCHEM2AER(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YPAER_ACLIB%NCHEM2AER)   
  REAL(KIND=JPRB),INTENT(INOUT)  :: PTENCHEM2AER(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YPAER_ACLIB%NCHEM2AER)   

  REAL(KIND=JPRB), INTENT(INOUT) :: PAERD(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(INOUT) :: PTENDAERO(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NAERO)
  REAL(KIND=JPRB), INTENT(INOUT) :: PP1EZDIAG(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NGFL_EZDIAG)
  TYPE(TAEROUT_ACLIB), INTENT(INOUT) :: YLAEROUT_ACLIB

  REAL(KIND=JPRB), INTENT(OUT)   :: PAEROM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NAERO)

  ! Single scattering albedo of dust (points,lev,wvl) :
  REAL(KIND=JPRB), INTENT(OUT)   :: PPIZA_DST(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH)
  ! Assymetry factor for dust (points,lev,wvl) :
  REAL(KIND=JPRB), INTENT(OUT)   :: PCGA_DST(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH)
  ! tau/tau_{550} dust (points,lev,wvl) :
  REAL(KIND=JPRB), INTENT(OUT)   :: PTAUREL_DST(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH)

  INTEGER(KIND=JPIM) :: IEZDIAG_CHEM
  REAL(KIND=JPRB) :: ZPEZDIAG(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_GCONF%YGFL%NGFL_EZDIAG - KIOFF_MFSHAL + 1)

  INTEGER(KIND=JPIM) :: JLON, JLEV, JGFL, KBL
  INTEGER(KIND=JPIM), PARAMETER :: IKL = -1

  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

!-- aerosol-related quantities for tactic
  INTEGER(KIND=JPIM),PARAMETER    :: JPTILES=8_JPIM
  REAL(KIND=JPRB)   :: ZCI(YDCPG_BNDS%KFDIA) ! sea ice fraction in ecmwf physics, but here sea ice
  REAL(KIND=JPRB)   :: ZWS(YDCPG_BNDS%KFDIA) ! "humidity" in top layer
  REAL(KIND=JPRB)   :: ZFRTI(YDCPG_BNDS%KFDIA,JPTILES) ! bare soil fraction
  REAL(KIND=JPRB)   :: ZCLK(YDCPG_BNDS%KFDIA) ! Lake fraction (set to 0 temporarily...)
  REAL(KIND=JPRB), DIMENSION(YDCPG_BNDS%KFDIA)                               :: ZAERLTS, ZAERSCC 
  REAL(KIND=JPRB)   :: ZAERZ0(YDCPG_BNDS%KFDIA)
  REAL(KIND=JPRB)   :: ZAERCFLX(YDCPG_BNDS%KFDIA,YDMODEL%YRML_GCONF%YGFL%NAERO),ZAERDDVLC(YDCPG_BNDS%KFDIA,YDMODEL%YRML_GCONF%YGFL%NAERO)
  REAL(KIND=JPRB)   :: ZGELAT(YDCPG_BNDS%KFDIA)

  ! Precipitation flux
  REAL(KIND=JPRB),DIMENSION(YDCPG_BNDS%KFDIA,0:YDCPG_OPTS%KFLEVG)           :: ZLCVPFLX   ! Local value of ZLCVPFLX
  REAL(KIND=JPRB),DIMENSION(YDCPG_BNDS%KFDIA,0:YDCPG_OPTS%KFLEVG)           :: ZLSTPFLX   ! Local value of ZLSTPFLX 
  REAL(KIND=JPRB),DIMENSION(YDCPG_BNDS%KFDIA,0:YDCPG_OPTS%KFLEVG)           :: ZSCVPFLX   ! Local value of ZSCVPFLX
  REAL(KIND=JPRB),DIMENSION(YDCPG_BNDS%KFDIA,0:YDCPG_OPTS%KFLEVG)           :: ZSSTPFLX   ! Local value of ZSSTPFLX

  REAL(KIND=JPRB),DIMENSION(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)           :: ZTP   ! Temperature for ACLIB
  
  ! Surfex variable
  REAL(KIND=JPRB), DIMENSION(YDCPG_BNDS%KFDIA)    :: ZSEA
  REAL(KIND=JPRB), DIMENSION(YDCPG_BNDS%KFDIA)    :: PLSM
  REAL(KIND=JPRB), DIMENSION(YDCPG_BNDS%KFDIA)    :: ZNATURE

  !------------------------------------------------------------------

#include "aro_mnhdust.h"
#include "aer_main2.intfb.h"
  !------------------------------------------------------------------

  IF (LHOOK) CALL DR_HOOK('APL_AROME_DUST_MOD:APL_AROME_DUST', 0, ZHOOK_HANDLE)
  !
  ASSOCIATE(YDPHY1=>YDMODEL%YRML_PHY_MF%YRPHY1)
  ASSOCIATE(TMERGL=>YDPHY1%TMERGL, GCONV=>YDPHY1%GCONV, RD1=>YDPHY1%RD1, NDDUST=>YDMODEL%YRML_PHY_AER%YREAERSRC%NDDUST,RG=>YDCST%RG,NAERO=>YDMODEL%YRML_GCONF%YGFL%NAERO)
  
  IEZDIAG_CHEM = YDMODEL%YRML_GCONF%YGFL%NGFL_EZDIAG-KIOFF_MFSHAL + 1
  PAEROM(:,:,:) = PAEROMIN(:,:,:)

  IF(YDMODEL%YRML_PHY_MF%YRARPHY%LRDUST) THEN
    ! input dust scalar concentration in ppp from
    CALL ARO_MNHDUST(IKL, YDCPG_BNDS, YDCPG_OPTS%KFLEVG, &
                  & YDMF_PHYS_BASE_STATE,&
                  & YDCPG_DYN0,&
                  & NSV_DSTEND-NSV_DSTBEG+1, YDCPG_OPTS%ZDTPHY, &
                  & PAEROMIN(:,:,NSV_DSTBEG:NSV_DSTEND), PZZ, PDZZ, PRHM, &
                  & PPABSM(:, 1:YDCPG_OPTS%KFLEVG), PTHM(:, 1:YDCPG_OPTS%KFLEVG), PRHODREFM(:, 1:YDCPG_OPTS%KFLEVG), &
                  & YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH, YDCPG_OPTS%NSTEP+1, PAEROM(:,:,NSV_DSTBEG:NSV_DSTEND), &
                  & PPIZA_DST, PCGA_DST, PTAUREL_DST, &
                  & PAERD, IEZDIAG_CHEM, ZPEZDIAG, PTENDAERO(:,:,NSV_DSTBEG:NSV_DSTEND))
    !
    PP1EZDIAG(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, 1:YDCPG_OPTS%KFLEVG, KIOFF_MFSHAL:YDMODEL%YRML_GCONF%YGFL%NGFL_EZDIAG) = ZPEZDIAG
    !

    ! return to tendency
    DO JGFL = NSV_DSTBEG,NSV_DSTEND
      DO JLEV = 1, YDCPG_OPTS%KFLEVG
        DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
          PTENDAERO(JLON,JLEV,JGFL) = PTENDAERO(JLON,JLEV,JGFL) + (PAEROM(JLON,JLEV,JGFL) - PAEROMIN(JLON,JLEV,JGFL))/PDT
        ENDDO
      ENDDO
    ENDDO

  ENDIF

  ! Configuration with tactic
  IF (TRIM(YDMODEL%YRML_CHEM%YRCOMPO%AERO_SCHEME)=="tactic") THEN

    ! Get Surfex buffer
    KBL = YDCPG_BNDS%KBL
    YSURFEX_ARO_CUR => YSURFEX_ARO_ALL (KBL)

    CALL GET_SURF_VAR_N &
    (YSURFEX_ARO_CUR%FM, YSURFEX_ARO_CUR%IM,    &
    YSURFEX_ARO_CUR%SM, YSURFEX_ARO_CUR%TM, &
    YSURFEX_ARO_CUR%WM, YSURFEX_ARO_CUR%DUO,     &
    YSURFEX_ARO_CUR%DU, YSURFEX_ARO_CUR%UG,  &
    YSURFEX_ARO_CUR%U,      YSURFEX_ARO_CUR%USS,     &
    YSURFEX_ARO_CUR%SM%S,                            &
    CPROGRAM_MSE, YDCPG_BNDS%KFDIA,1, &
    PNATURE=ZNATURE, PSEA=ZSEA)    ! Land sea mask

    ! convert LSM from 1=sea to 0=sea
    PLSM = 1.-ZSEA

    ! Latitude
    DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      ZGELAT(JLON) = ASIN(YDVARS%GEOMETRY%GEMU%T0(JLON))
    ENDDO

    ! initialise precipitation at zero (for first level)
    ZLCVPFLX(:,:) = 0.0
    ZLSTPFLX(:,:) = 0.0
    ZSCVPFLX(:,:) = 0.0
    ZSSTPFLX(:,:) = 0.0

  ! Liquid precipitation flux for AER_ACLIB for higheest levels only
    ZLCVPFLX(:,2:) = PFPR(:,:,3)
    ZLSTPFLX(:,2:) = 0.
  
  ! Solid precipitation flux for AER_ACLIB
    ZSCVPFLX(:,2:) = PFPR(:,:,5)+PFPR(:,:,6)
    ZSSTPFLX(:,2:) = 0.

  ! Temperature computation for AER_ACLIB
    ZTP(:,:)=0.
    ZTP(:,:)=PTHM(:,:)*(PPABSM(:,:) / YDCST_ACLIB%RP00)**(YDCST_ACLIB%RRD/YDCST_ACLIB%RCPD)
  

    CALL AER_MAIN2( YDCST_ACLIB=YDCST_ACLIB, YPAER_ACLIB=YPAER_ACLIB, &
      & YAEROSOLS=YAEROSOLS,&
      & YPCHEM_ACLIB=YPCHEM_ACLIB, YCHEMS=YCHEMS, &
      & KIDIA=YDCPG_BNDS%KIDIA, &
      & KFDIA=YDCPG_BNDS%KFDIA, &
      & KLUOUT=NULOUT, &
      & KLON=YDCPG_BNDS%KFDIA, KLEV=YDCPG_OPTS%KFLEVG, PTSTEP=YDCPG_OPTS%ZDTPHY, PGELAT=ZGELAT, &
      & PAP=PPABSM(:, 1:YDCPG_OPTS%KFLEVG), &         ! FULL-LEVEL PRESSURE
      & PAPH=YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:), &     ! HALF-LEVEL PRESSURE    
      & PAPHI=YDMF_PHYS_BASE_STATE%YCPG_DYN%PHI(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:), &    ! GEOPOTENTIAL ON HALF-LEVELS
      & PDELP=YDCPG_DYN0%XYB%DELP(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:), &                  ! DELTA PRESSURE
      & PTP=ZTP,  &                                                                        ! FULL-LEVEL TEMPERATURE
      & PVERVEL=YDMF_PHYS_BASE_STATE%YCPG_PHY%W(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:),&     ! FULL-LEVEL VERTICAL VELOCITY
      & PRH=PRHM, &                                                  ! RELATIVE HUMIDITY
      & PLSM=PLSM(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA),&               ! LAND-SEA MASK
      & PLCVPFLX=ZLCVPFLX, &               ! LIQUID CONVECTIVE PRECIPITATION FLUX (kg.m-2.s-1)
      & PLSTPFLX=ZLSTPFLX, &               ! LIQUID STRATIFORM PRECIPITATION FLUX (kg.m-2.s-1)
      & PSCVPFLX=ZSCVPFLX, &               ! SOLID  CONVECTIVE PRECIPITATION FLUX (kg.m-2.s-1)
      & PSSTPFLX=ZSSTPFLX, &               ! SOLID  STRATIFORM PRECIPITATION FLUX (kg.m-2.s-1)  
      & PCLCOV=PNEBMNH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:)*0., &                      ! CLOUD COVER
      & PCLWATL=YDMF_PHYS_BASE_STATE%L(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:), &             ! LIQUID WATER CONTENT         (kg/kg)
      & PCLWATS=YDMF_PHYS_BASE_STATE%I(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:), &             ! SOLID  WATER CONTENT         (kg/kg)
      & PAER=PAEROM,&                                                                      ! AEROSOL CONCENTRATION
      & PTENAER=PTENDAERO(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:,:),&                         ! AEROSOL TENDENCY
      & YAEROUT_ACLIB=YLAEROUT_ACLIB,&                ! STRUCTURE FOR AEROSOL OUTPUT
      & PCHEM2AER=PCHEM2AER, &                        ! CHEMICAL CONCENTRATIONS TO BE USED FOR AEROSOL FORMATION
      & PTENCHEM2AER=PTENCHEM2AER)                    ! CHEMICAL TENDENCIES UPDATED FROM AEROSOL FORMATION


  DEALLOCATE(YLAEROUT_ACLIB%PLOAD      )
  DEALLOCATE(YLAEROUT_ACLIB%PEMIS      )
  DEALLOCATE(YLAEROUT_ACLIB%PDRYDEP    )
  DEALLOCATE(YLAEROUT_ACLIB%PSEDIM     )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEP    )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEPBCR )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEPBCS )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEPINR )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEPINS )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEPRER )
  DEALLOCATE(YLAEROUT_ACLIB%PWETDEPRES )
  DEALLOCATE(YLAEROUT_ACLIB%PAERAODS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PAERAAODS  )   
  DEALLOCATE(YLAEROUT_ACLIB%PAERACAODS )   
  DEALLOCATE(YLAEROUT_ACLIB%PAEREXTS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PAERSCATS  )   
  DEALLOCATE(YLAEROUT_ACLIB%PTYPAODS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PTYPAAODS  )   
  DEALLOCATE(YLAEROUT_ACLIB%PTYPACAODS )   
  DEALLOCATE(YLAEROUT_ACLIB%PTYPEXTS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PTYPSCATS  )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTAODS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTAODLT1S)   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTAAODS  )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTACAODS )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTEXTS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTSCATS  )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTSSAS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PTOTASYS   )   
  DEALLOCATE(YLAEROUT_ACLIB%PTAUAER    )
  DEALLOCATE(YLAEROUT_ACLIB%POMGAER    )
  DEALLOCATE(YLAEROUT_ACLIB%PASYAER    )
  DEALLOCATE(YLAEROUT_ACLIB%PTAUAERL   )
  DEALLOCATE(YLAEROUT_ACLIB%POMGAERL   )
  DEALLOCATE(YLAEROUT_ACLIB%PASYAERL   )
  DEALLOCATE(YLAEROUT_ACLIB%PMAERIND   )

  ENDIF

  END ASSOCIATE
  END ASSOCIATE

  IF (LHOOK) CALL DR_HOOK('APL_AROME_DUST_MOD:APL_AROME_DUST', 1, ZHOOK_HANDLE)

END SUBROUTINE APL_AROME_DUST
