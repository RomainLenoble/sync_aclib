SUBROUTINE APL_AROME_RADIATION(YDCST, YDMODEL, YDMF_PHYS_BASE_STATE, YDMF_PHYS_SURF, YDMF_PHYS, YDGEOMETRY, &
                             & YDCPG_BNDS, YDCPG_OPTS, YDCPG_MISC, YDCPG_GPAR, YDVARS, YDSURF, &
                             & YSPP_ALL, YDDDH, &
                             & LDMSE, LDSFORCS, &
                             & PALB_FORC, PEMIS_FORC, PADTMS, &
                             & PCPM, PQVM, PTM, &
                             & PQIM, PQSM, PQGM, PQCM, PQRM, PQHM, &
                             & PEXNREFM, PRDG_MU0, PRDG_SOLO, PAERD, &
                             & PRDG_MU0M, PRDG_MU0LU, PCLDROP, &
                             & PPIZA_DST, PCGA_DST, PTAUREL_DST, PAEROM, &
                             & PTENDT, &
                             & PEMIS, PTSURF, &
                             & PQSAT, PALBP, PALBD, &
                             & PZS_FSWDIR, PZS_FSWDIF, &
                             & PDTHRAD, PP1EZDIAG)

!**** *APL_AROME_RADIATION* - Setup and call Arome radiation

!     Author.
!     -------
!      Rolf Heilemann Myhre *Met Norway*
!      Original : 01-09-2023
!      See APL_AROME for modification history

!-----------------------------------------------------------------------

! -   INPUT ARGUMENTS.
!     -------------------
!
!   YDCST:                Model constants
!   YDMODEL:              Model configuration settings
!   YDMF_PHYS_BASE_STATE:
!   YDMF_PHYS_SURF:       Surface fields
!   YDMF_PHYS:            Physics fields
!   YDGEOMETRY:           Geomtery settings from IFS model
!   YDCPG_BNDS:           Array dimensions and bounds
!   YDCPG_OPTS:           Various dimensions
!   YDCPG_MISC:
!   YDCPG_GPAR:
!   YDVARS:               Persistent fields
!   YDSURF:               Various surface fields and, declarations, and definitions
!   YSPP_ALL:             SPP fields and settings
!   YDDDH:                DDH fields and settings
!
!   PTM:    Temperature.
!   PCPM:   Specific heat at constant pressure for air
!   PTENDT: Temperature tendency
!
!   YDDDH:                DDH fields and settings
!

  USE PARKIND1, ONLY: JPRB, JPRD, JPIM

  USE YOMCST,                      ONLY: TCST
  USE TYPE_MODEL,                  ONLY: MODEL
  USE MF_PHYS_BASE_STATE_TYPE_MOD, ONLY: MF_PHYS_BASE_STATE_TYPE
  USE MF_PHYS_SURFACE_TYPE_MOD,    ONLY: MF_PHYS_SURF_TYPE
  USE MF_PHYS_TYPE_MOD,            ONLY: MF_PHYS_TYPE
  USE GEOMETRY_MOD,                ONLY: GEOMETRY
  USE CPG_OPTS_TYPE_MOD,           ONLY: CPG_BNDS_TYPE, CPG_OPTS_TYPE
  USE CPG_TYPE_MOD,                ONLY: CPG_MISC_TYPE, CPG_GPAR_TYPE
  USE SPP_MOD_TYPE,                ONLY: UA_PHYS_SPP_VARS, APPLY_SPP
  USE FIELD_VARIABLES_MOD,         ONLY: FIELD_VARIABLES
  USE SURFACE_FIELDS_MIX,          ONLY: TSURF

  USE DDH_MIX,                     ONLY: NEW_ADD_FIELD_3D, TYP_DDH

  USE YOMHOOK,                     ONLY: LHOOK, DR_HOOK, JPHOOK

  IMPLICIT NONE

  TYPE(TCST),                    INTENT(IN)    :: YDCST
  TYPE(MODEL),                   INTENT(IN)    :: YDMODEL
  TYPE(MF_PHYS_BASE_STATE_TYPE), INTENT(IN)    :: YDMF_PHYS_BASE_STATE
  TYPE(MF_PHYS_SURF_TYPE),       INTENT(IN)    :: YDMF_PHYS_SURF
  TYPE(MF_PHYS_TYPE),            INTENT(IN)    :: YDMF_PHYS
  TYPE(GEOMETRY),                INTENT(IN)    :: YDGEOMETRY
  TYPE(CPG_BNDS_TYPE),           INTENT(IN)    :: YDCPG_BNDS
  TYPE(CPG_OPTS_TYPE),           INTENT(IN)    :: YDCPG_OPTS
  TYPE(CPG_MISC_TYPE),           INTENT(IN)    :: YDCPG_MISC
  TYPE(CPG_GPAR_TYPE),           INTENT(IN)    :: YDCPG_GPAR
  TYPE(FIELD_VARIABLES),         INTENT(INOUT) :: YDVARS
  TYPE(TSURF),                   INTENT(IN)    :: YDSURF

  TYPE(UA_PHYS_SPP_VARS),        INTENT(INOUT) :: YSPP_ALL
  TYPE(TYP_DDH),                 INTENT(INOUT) :: YDDDH


  LOGICAL,         INTENT(IN)    :: LDMSE
  LOGICAL,         INTENT(IN)    :: LDSFORCS

  REAL(KIND=JPRB), INTENT(IN)    :: PALB_FORC
  REAL(KIND=JPRB), INTENT(IN)    :: PEMIS_FORC
  REAL(KIND=JPRB), INTENT(IN)    :: PADTMS

  REAL(KIND=JPRB), INTENT(IN)    :: PCPM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PQVM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PTM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB), INTENT(IN)    :: PQIM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PQSM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PQGM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PQCM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PQRM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PQHM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB), INTENT(IN)    :: PEXNREFM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(IN)    :: PRDG_MU0(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB), INTENT(IN)    :: PRDG_SOLO(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB), INTENT(IN)    :: PAERD(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB), INTENT(IN)    :: PRDG_MU0M(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB), INTENT(IN)    :: PRDG_MU0LU(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB), INTENT(IN)    :: PCLDROP(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)

  ! Single scattering albedo of dust (points,lev,wvl) :
  REAL(KIND=JPRB), INTENT(IN)    :: PPIZA_DST(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH)
  ! Assymetry factor for dust (points,lev,wvl) :
  REAL(KIND=JPRB), INTENT(IN)    :: PCGA_DST(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH)
  ! tau/tau_{550} dust (points,lev,wvl) :
  REAL(KIND=JPRB), INTENT(IN)    :: PTAUREL_DST(YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG,YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH)
! Aerosol species (MR:Mass mixing ratio, NC:number condentration)
  REAL(KIND=JPRB), INTENT(IN)    :: PAEROM(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_GCONF%YGFL%NAERO)

  REAL(KIND=JPRB), INTENT(INOUT) :: PTENDT(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG) ! temperature tendency

  REAL(KIND=JPRB), INTENT(OUT)   :: PEMIS(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB), INTENT(OUT)   :: PTSURF(YDCPG_OPTS%KLON)

  REAL(KIND=JPRB), INTENT(OUT)   :: PQSAT(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(OUT)   :: PALBP(YDCPG_OPTS%KLON, YDMODEL%YRML_PHY_RAD%YRERAD%NSW)
  REAL(KIND=JPRB), INTENT(OUT)   :: PALBD(YDCPG_OPTS%KLON, YDMODEL%YRML_PHY_RAD%YRERAD%NSW)

  REAL(KIND=JPRB), INTENT(OUT)   :: PZS_FSWDIR(YDCPG_OPTS%KLON, YDMODEL%YRML_PHY_RAD%YRERAD%NSW)
  REAL(KIND=JPRB), INTENT(OUT)   :: PZS_FSWDIF(YDCPG_OPTS%KLON, YDMODEL%YRML_PHY_RAD%YRERAD%NSW)

  REAL(KIND=JPRB), INTENT(OUT)   :: PDTHRAD(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB), INTENT(OUT)   :: PP1EZDIAG(YDCPG_BNDS%KFDIA, YDCPG_OPTS%KFLEVG)

  ! Perturbed radiation-cloud interaction coef
  REAL(KIND=JPRB) :: ZRADGR(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZRADSN(YDCPG_OPTS%KLON)

  REAL(KIND=JPRB) :: ZALBD1(YDCPG_OPTS%KLON)

  REAL(KIND=JPRB) :: ZQV(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQICE(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQLIQ(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB) :: ZGEOSLC(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZLH(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZLSCPE(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQW(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZTW(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZTH(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG+1)

  REAL(KIND=JPRB) :: ZAER(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, 6)
  REAL(KIND=JPRB) :: ZAERINDS(YDCPG_OPTS%KLON,YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB) :: ZCTRSO(YDCPG_OPTS%KLON, 2)
  REAL(KIND=JPRB) :: ZCEMTR(YDCPG_OPTS%KLON, 2)

  REAL(KIND=JPRB) :: ZTRSOD(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZTRSODIR(YDCPG_OPTS%KLON, YDMODEL%YRML_PHY_RAD%YRERAD%NSW)
  REAL(KIND=JPRB) :: ZTRSODIF(YDCPG_OPTS%KLON, YDMODEL%YRML_PHY_RAD%YRERAD%NSW)

  REAL(KIND=JPRB) :: ZDUM(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZGELAM(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZCHTIX(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG+1)
  REAL(KIND=JPRB) :: ZRAER(YDCPG_OPTS%KLON,6,YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRD) :: ZGEMU_D(YDCPG_OPTS%KLON)  ! double precision version of YDVARS%GEOMETRY%GEMU%T0, for RADACT

  REAL(KIND=JPRB) :: ZQO3(YDCPG_OPTS%KLON, 0:YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB) :: ZQCO2(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQCH4(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQN2O(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQNO2(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQC11(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQC12(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQC22(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZQCL4(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)

  REAL(KIND=JPRB) :: ZFSDNN(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZFSDNV(YDCPG_OPTS%KLON)

  REAL(KIND=JPRB) :: ZFRSOLU(YDCPG_OPTS%KLON)

  REAL(KIND=JPRB) :: ZTENT(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZSUDU(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZSDUR(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZDSRP(YDCPG_OPTS%KLON)
  REAL(KIND=JPRB) :: ZFRSOFS(YDCPG_OPTS%KLON)

  REAL(KIND=JPRB) :: ZROZ(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)
  REAL(KIND=JPRB) :: ZAERO(YDCPG_OPTS%KLON,YDCPG_OPTS%KFLEVG, 12)
  REAL(KIND=JPRB) :: ZAEROCPL(YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, YDMODEL%YRML_PHY_RAD%YRERAD%NTLW, 6)

  REAL(KIND=JPRB) :: ZAEMMR3D(YDMODEL%YRML_PHY_MF%YRAIOP%NAEROMR, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG)

  INTEGER(KIND=JPIM) :: JLON, JLEV, JSW, JK, JAE

  INTEGER(KIND=JPIM) :: IAERO

  REAL(KIND=JPRB) :: ZSALBCOR

  REAL(KIND=JPHOOK) :: ZHOOK_HANDLE

  !------------------------------------------------------------------

#include "actqsat.intfb.h"
#include "radaer.intfb.h"
#include "radact.intfb.h"
#include "aeropt.intfb.h"
#include "radghg.intfb.h"
#include "radozc.intfb.h"
#include "suozon.intfb.h"
#include "recmwf.intfb.h"
#include "radheat.intfb.h"

  !------------------------------------------------------------------

  IF (LHOOK) CALL DR_HOOK('APL_AROME_RADIATION_MOD:APL_AROME_RADIATION', 0, ZHOOK_HANDLE)

  ! Preparation of input humidity, clouds, albedo, aerosol, atmospheric gases for any radiation scheme at every time step

  ! test de coherence sur le nombre de bandes spectrales entre ce qui sort de
  ! la surface et ce qu'attend le rayonnement
  IF( YDMODEL%YRML_PHY_MF%YRPARAR%NSWB_MNH /= YDMODEL%YRML_PHY_RAD%YRERAD%NSW) THEN
    CALL ABOR1 (' NSWB_MNH must be equal to NSW !')
  ENDIF

  IAERO = 0_JPIM

  ! compute saturated specific humidity
  CALL ACTQSAT(YDCST, YDMODEL%YRML_PHY_MF%YRPHY, YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, &
             & YDMODEL%YRML_PHY_MF%YRTOPH%NTQSAT, YDCPG_OPTS%KFLEVG, YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF, &
             & PCPM, PQVM, PTM, ZGEOSLC, ZLH, ZLSCPE, PQSAT, ZQW, YDCPG_MISC%RH, ZTW)

  IF (YSPP_ALL%YSPP_RADGR%LPERT) THEN
    CALL APPLY_SPP(YSPP_ALL%YSPP_RADGR, &
                 & YDCPG_OPTS%KLON, YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, &
                 & YDMODEL%YRML_PHY_MF%YRPARAR%RADGR, ZRADGR)
  ELSE
    DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      ZRADGR(JLON) = YDMODEL%YRML_PHY_MF%YRPARAR%RADGR
    ENDDO
  ENDIF

  IF (YSPP_ALL%YSPP_RADSN%LPERT) THEN
    CALL APPLY_SPP(YSPP_ALL%YSPP_RADSN, &
                 & YDCPG_OPTS%KLON, YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, &
                 & YDMODEL%YRML_PHY_MF%YRPARAR%RADSN, ZRADSN)
  ELSE
    DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      ZRADSN(JLON) = YDMODEL%YRML_PHY_MF%YRPARAR%RADSN
    ENDDO
  ENDIF

  ! initialisation des humidite (dans le rayonnement, l'eau liquide nuageuse
  ! et la glace sont donne par des hu par rapport au gaz.
  ! (qi/qa+qv pour ice par ex. C'est donc different de ri)
  DO JLEV=YDCPG_OPTS%KTDIA,YDCPG_OPTS%KFLEVG
    DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      ZQICE(JLON,JLEV) = MAX(0.0_JPRB, (PQIM(JLON,JLEV) + PQSM(JLON,JLEV)*ZRADSN(JLON) + PQGM(JLON,JLEV)*ZRADGR(JLON))/&
      & (1.0_JPRB-PQIM(JLON,JLEV)-PQCM(JLON,JLEV)-PQRM(JLON,JLEV)-PQGM(JLON,JLEV)-PQSM(JLON,JLEV)-PQHM(JLON,JLEV)))

      ZQLIQ(JLON,JLEV) = MAX(0.0_JPRB, PQCM(JLON,JLEV)/&
      & (1.0_JPRB-PQIM(JLON,JLEV)-PQCM(JLON,JLEV)-PQRM(JLON,JLEV)-PQGM(JLON,JLEV)-PQSM(JLON,JLEV)-PQHM(JLON,JLEV)))

      ZQV(JLON,JLEV) = MAX(0.0_JPRB, PQVM(JLON,JLEV)/&
      & (1.0_JPRB-PQIM(JLON,JLEV)-PQCM(JLON,JLEV)-PQRM(JLON,JLEV)-PQGM(JLON,JLEV)-PQSM(JLON,JLEV)-PQHM(JLON,JLEV)))
    ENDDO
  ENDDO

  ! store cloud water content for RTTOV
  IF(YDMODEL%YRML_GCONF%YGFL%YIRAD%LGP) THEN
    YDVARS%IRAD%T1(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:) = ZQICE(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:)
  ENDIF

  IF(YDMODEL%YRML_GCONF%YGFL%YLRAD%LGP) THEN
    YDVARS%LRAD%T1(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:) = ZQLIQ(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,:)
  ENDIF

  ! Albedo dans les intervalles, direct (parallel) et diffus (diffuse).
  IF (YDMODEL%YRML_PHY_RAD%YRERAD%NSW==6 .OR. YDMODEL%YRML_PHY_RAD%YRERAD%NSW==1) THEN

    IF (LDMSE) THEN
      DO JSW = 1, YDMODEL%YRML_PHY_RAD%YRERAD%NSW
        PALBP(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JSW) = YDCPG_GPAR%ALBDIR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JSW)
        PALBD(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JSW) = YDCPG_GPAR%ALBSCA(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JSW)
        IF (YDMODEL%YRML_PHY_MF%YRPHY%LHLRADUPD) THEN
          DO JLON=YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
            ZSALBCOR = 0.2_JPRB/(1._JPRB + PRDG_MU0(JLON)) - 0.12_JPRB
            PALBP(JLON,JSW) = PALBD(JLON,JSW) + ZSALBCOR
          ENDDO
        ENDIF
      ENDDO
    ELSEIF (LDSFORCS) THEN
      DO JSW = 1, YDMODEL%YRML_PHY_RAD%YRERAD%NSW
        PALBP(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JSW) = PALB_FORC
        PALBD(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JSW) = PALB_FORC
      ENDDO
    ELSE
      !pour pouvoir tourner sans la surface
      DO JSW=1, YDMODEL%YRML_PHY_RAD%YRERAD%NSW
        PALBP(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JSW)=YDMF_PHYS_SURF%GSD_VF%PALBF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
        PALBD(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JSW)=YDMF_PHYS_SURF%GSD_VF%PALBF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
      ENDDO
    ENDIF

    ! Spectral average albedo done with RSUN2 weights,
    ! to be applied for ACRANEB2 which use a single solar spectral band
    IF (YDMODEL%YRML_PHY_MF%YRPHY%LHLRADUPD) THEN
      ZALBD1(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0._JPRB
      DO JSW = 1, YDMODEL%YRML_PHY_RAD%YRERAD%NSW
        DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
          ZALBD1(JLON) = ZALBD1(JLON) + YDMODEL%YRML_PHY_RAD%YRESWRT%RSUN2(JSW)*PALBD(JLON,JSW)
        ENDDO
      ENDDO
    ELSE
      ZALBD1(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=YDCPG_GPAR%ALBSCA(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1)
    ENDIF

  ELSE
    CALL ABOR1 ('ALBEDO FOR NSW/= 1 or 6 not defined in apl_arome')
  ENDIF

  ! all albedo operations
  IF (LDMSE) THEN
    PEMIS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=YDCPG_GPAR%VEMIS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    PTSURF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=YDCPG_GPAR%VTS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    ! protection for E Zone, Where surface scheme send back EMIS and T =0
    ! the protection in aro_ground_paramn is not sufficient !!! WHY ??
    DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      IF (PEMIS(JLON)==0._JPRB) THEN
        PEMIS(JLON)=1.0_JPRB
        PTSURF(JLON)=288.0_JPRB
      ENDIF
    ENDDO
  ELSEIF (LDSFORCS) THEN
    PEMIS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=PEMIS_FORC
  ELSE
    PEMIS(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.5_JPRB ! value 0.5 is suspicious
    PTSURF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=PTM(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG)
  ENDIF !LDMSE EMIS

  ! NRT aerosol
  IF (YDMODEL%YRML_PHY_MF%YRPHY%LAEROMMR) THEN
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        DO JAE = 1, YDMODEL%YRML_PHY_MF%YRAIOP%NAEROMR
          ZAEMMR3D(JAE, JLON, JLEV) = 0._JPRB
        ENDDO
      ENDDO
    ENDDO
  ENDIF

  IF (YDMODEL%YRML_PHY_MF%YRPHY%LAERONRT) THEN
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        DO JAE = 1, YDMODEL%YRML_PHY_MF%YRAIOP%NAEROMR
          ZAEMMR3D(JAE, JLON, JLEV) = &
          & MAX(PAEROM(JLON, JLEV, JAE)*YDMF_PHYS_BASE_STATE%YCPG_PHY%XYB%DELP(JLON,JLEV)*1._JPRB/YDCST%RG, 0.0_JPRB)
        ENDDO
      ENDDO
    ENDDO
  ELSEIF (YDMODEL%YRML_PHY_RAD%YRERAD%NAER >= 1 .AND. YDMODEL%YRML_PHY_RAD%YRERAD%NAERMACC == 0) THEN
    IF(YDSURF%YSD_VAD%NUMFLDS >= 4) THEN

      CALL RADAER (YDMODEL%YRML_PHY_RAD%YREAERD, YDMODEL%YRML_PHY_RAD%YRERAD, YDMODEL%YRML_PHY_MF%YRPHY, &
      & YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, &
      & YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE, YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF, &
      & PTM, PTSURF, YDMF_PHYS_SURF%GSD_VA%PSEA, YDMF_PHYS_SURF%GSD_VA%PLAN, YDMF_PHYS_SURF%GSD_VA%PSOO,           &
      & YDMF_PHYS_SURF%GSD_VA%PDES, YDMF_PHYS_SURF%GSD_VA%PSUL, YDMF_PHYS_SURF%GSD_VA%PVOL, ZAER,                  &
      & ZAERINDS)

    ELSE
      CALL ABOR1('APL_AROME: PB AEROSOLS!')
      ! NB : this abort excludes the use of radact. REK.
    ENDIF
    ELSEIF (YDMODEL%YRML_PHY_RAD%YRERAD%NAERMACC==1 .AND. .NOT.YDMODEL%YRML_PHY_RAD%YREAERATM%LAERONRTR) THEN

    !AEROSOLS from MACC (NAERMACC=1)
    ZDUM(:,:) = 1._JPRB
    ! in E Zone, there are YDVARS%GEOMETRY%GEMU%T0 < 0.
    ZGELAM=YDVARS%GEOMETRY%GELAM%T0
    DO JLON=YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
      IF (ZGELAM(JLON) < 0._JPRB) THEN
        ZGELAM(JLON) = ZGELAM(JLON) + 2*YDCST%RPI
      ENDIF
    ENDDO

    ! Init ZCHTIX
    ! Warning YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE is 0:YDCPG_OPTS%KFLEVG here whereas in radintg it is
    ! 1:YDCPG_OPTS%KFLEVG+1
    DO JK=2,YDCPG_OPTS%KFLEVG
      ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK) = (PTM(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1) &
      & * YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1)&
      & *(YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK)  &
      & - YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1))&
      & + PTM(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK) &
      & * YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK) &
      & *(YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1)&
      & - YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1)))&
      & *(1.0_JPRB/(YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1) &
      & *(YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK) &
      & - YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK-1))))

      ZCHTIX(1:YDCPG_OPTS%KLON,JK) = ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JK)
    ENDDO

    ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1) = PTM(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1) &
                                           & - YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1) &
                                           & * (PTM(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1) &
                                           & - ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,2)) &
                                           & / (YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1) &
                                           & - YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1))

    ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG+1)=PTSURF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)
    ZCHTIX(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG+1)=ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,YDCPG_OPTS%KFLEVG+1)
    ZCHTIX(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1)=ZTH(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1)
    IAERO   = SIZE(ZAERO,3)
    ZGEMU_D = REAL(YDVARS%GEOMETRY%GEMU%T0,JPRD)

    CALL RADACT(YDMODEL%YRML_PHY_RAD%YREAERD, YDMODEL%YRML_PHY_RAD%YRERAD, YDMODEL%YRML_PHY_AER%YREAERSNK, &
    & YDMODEL%YRML_GCONF%YRRIP, YDMODEL%YRML_GCONF%YRSPP_CONFIG, &
    & YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, &
    & 1, YDCPG_OPTS%KLON, YDCPG_OPTS%KLON, 0, 1, &
    & YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE, ZGELAM, ZGEMU_D, YDVARS%GEOMETRY%GECLO%T0, YDVARS%GEOMETRY%GESLO%T0, ZCHTIX, &
    & PQVM, PQSAT, ZDUM, &
    & ZRAER, ZAERO, ZROZ)

    DO JAE = 1,6
      DO JK = 1,YDCPG_OPTS%KFLEVG
        DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
          ZAER(JLON,JK,JAE) = ZRAER(JLON,JAE,JK)
        ENDDO
      ENDDO
    ENDDO         
    ELSEIF (YDMODEL%YRML_PHY_RAD%YREAERATM%LAERONRTR) THEN
      IAERO = SIZE(ZAERO,3)
      ZAERO = MAX(PAEROM,0._JPRB)
    ENDIF
    
  IF (YDMODEL%YRML_PHY_MF%YRPHY%LAERONRT .OR. YDMODEL%YRML_PHY_MF%YRPHY%LAEROMMR) THEN
    ! optical properties of aerosol mixture for acraneb2 that is ready to use them,
    ! and diagnostic ZAER for IFS radiation, replacing those created by radaernrt above
    CALL AEROPT (YDMODEL%YRML_PHY_RAD%YRERAD, &
    & YDMODEL%YRML_PHY_MF%YRPHY, &
    & YDMODEL%YRML_PHY_MF%YRAIOP, &
    & YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, &
    & YDCPG_MISC%RH, ZAEMMR3D, &
    & ZAER, ZAERINDS)

    YDMF_PHYS_SURF%GSD_VA%PLAN(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB
    YDMF_PHYS_SURF%GSD_VA%PSEA(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB
    YDMF_PHYS_SURF%GSD_VA%PDES(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB
    YDMF_PHYS_SURF%GSD_VA%PSOO(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB
    YDMF_PHYS_SURF%GSD_VA%PVOL(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB
    YDMF_PHYS_SURF%GSD_VA%PSUL(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB
    DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
      DO JLEV=1,YDCPG_OPTS%KFLEVG
        YDMF_PHYS_SURF%GSD_VA%PLAN(JLON)=YDMF_PHYS_SURF%GSD_VA%PLAN(JLON)+ZAER(JLON,JLEV,1)   ! aesul included if given
        YDMF_PHYS_SURF%GSD_VA%PSEA(JLON)=YDMF_PHYS_SURF%GSD_VA%PSEA(JLON)+ZAER(JLON,JLEV,2)   ! sea
        YDMF_PHYS_SURF%GSD_VA%PDES(JLON)=YDMF_PHYS_SURF%GSD_VA%PDES(JLON)+ZAER(JLON,JLEV,3)   ! blown dust included if lrdust
        YDMF_PHYS_SURF%GSD_VA%PSOO(JLON)=YDMF_PHYS_SURF%GSD_VA%PSOO(JLON)+ZAER(JLON,JLEV,4)   ! urban
        YDMF_PHYS_SURF%GSD_VA%PVOL(JLON)=YDMF_PHYS_SURF%GSD_VA%PVOL(JLON)+ZAER(JLON,JLEV,5)   ! volcanic (sulphate) background
        YDMF_PHYS_SURF%GSD_VA%PSUL(JLON)=YDMF_PHYS_SURF%GSD_VA%PSUL(JLON)+ZAERINDS(JLON,JLEV) ! sulfates if exist separately
      ENDDO
    ENDDO
  ENDIF

  IF (YDMODEL%YRML_PHY_MF%YRARPHY%LRDUST.AND.YDMODEL%YRML_PHY_MF%YRPHY%LACLIB) THEN

    ! We use the extinction coefficient explicitly solved by ARO_MNHDUST
    ZAER(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1:YDCPG_OPTS%KFLEVG,3) = &
    & PAERD(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,1:YDCPG_OPTS%KFLEVG)

  ENDIF
  ! end of old or new aerosols

  ! initialization of ozone
  IF (YDMODEL%YRML_PHY_RAD%YRERAD%NOZOCL == 1) THEN

    ! as in IFS
    CALL RADOZC(YDMODEL%YRML_GCONF%YRRIP%YREOZOC, &
    & YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, 1, YDCPG_OPTS%KLON, &
    & 0, YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE, YDVARS%GEOMETRY%GEMU%T0, ZROZ)

    DO JK=1,YDCPG_OPTS%KFLEVG
      DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
        ZQO3(JLON,JK)=ZROZ(JLON,JK)/YDMF_PHYS_BASE_STATE%YCPG_PHY%XYB%DELP(JLON,JK)
      ENDDO
    ENDDO

  ELSEIF (YDMODEL%YRML_PHY_RAD%YRERAD%NOZOCL == 2) THEN

    ! as in ARPEGE (from clim profiles)
    CALL SUOZON(YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, ZQO3, &
    & .FALSE., YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE, YDMF_PHYS_BASE_STATE%YCPG_PHY%XYB%RDELP,    &
    & YDMODEL%YRML_PHY_MF%YRPHY%LO3ABC, YDMF_PHYS_SURF%GSD_VC%PA,                             &
    & YDMF_PHYS_SURF%GSD_VC%PB, YDMF_PHYS_SURF%GSD_VC%PC)

  ENDIF

  IF (YDMODEL%YRML_PHY_RAD%YRERAD%NOZOCL==3 .OR. YDMODEL%YRML_PHY_RAD%YRERAD%NOZOCL==4) THEN ! Clims MACC

    CALL RADGHG (YDMODEL%YRML_PHY_RAD%YRERAD, YDMODEL%YRML_GCONF%YRRIP,                        &
    & YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, YDCPG_OPTS%KLON, &
    & YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE,YDVARS%GEOMETRY%GEMU%T0,                               &
    & ZQCO2, ZQCH4, ZQN2O, ZQNO2, ZQC11, ZQC12, ZROZ, ZQC22, ZQCL4 )

    DO JK=1,YDCPG_OPTS%KFLEVG
      DO JLON=YDCPG_BNDS%KIDIA,YDCPG_BNDS%KFDIA
        ZQO3(JLON,JK) = ZROZ(JLON,JK)
      ENDDO
    ENDDO

  ENDIF

  ! Intermittent call to radiation interface
  IF (MOD(YDCPG_OPTS%NSTEP, YDMODEL%YRML_PHY_RAD%YRERAD%NRADFR) == 0) THEN

    CALL RECMWF(YDGEOMETRY%YRDIMV, YDMODEL, YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON, YDCPG_OPTS%KFLEVG, &
    & YDCPG_OPTS%KSW,                                                                                               &
    & YDMODEL%YRML_PHY_RAD%YRERAD%NOZOCL, YDMODEL%YRML_PHY_RAD%YRERAD%NAERMACC, IAERO,                              &
    & PALBD, PALBP, YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE, YDMF_PHYS_BASE_STATE%YCPG_PHY%PREF, YDVARS%A%T1,             &
    & ZQO3, ZQCO2, ZQCH4, ZQN2O, ZQNO2, ZQC11, ZQC12, ZQC22, ZQCL4,                                                 &
    & ZAER, ZAERO, ZAEROCPL, YDMF_PHYS_BASE_STATE%YCPG_PHY%XYB%DELP, PEMIS,                                         &
    & PRDG_MU0M, ZQV, PQSAT,                                                                                        &
    & ZQICE, ZQLIQ, PQSM, PQRM, YDMF_PHYS_SURF%GSD_VF%PLSM, PTM, PTSURF, YDMF_PHYS%RAD%EMTD, YDMF_PHYS%RAD%EMTU,    &
    & YDMF_PHYS%RAD%TRSW, YDMF_PHYS%OUT%FRTHC, YDMF_PHYS%OUT%FRTH, YDMF_PHYS%OUT%FRSOC, YDMF_PHYS%OUT%FRSO,         &
    & PZS_FSWDIR, PZS_FSWDIF, ZFSDNN, ZFSDNV, ZCTRSO, ZCEMTR, ZTRSOD, ZTRSODIR, ZTRSODIF,                           &
    & PPIZA_DST, PCGA_DST, PTAUREL_DST, ZAERINDS, YDVARS%GEOMETRY%GELAM%T0, YDVARS%GEOMETRY%GEMU%T0,                &
    & YDCPG_GPAR%SWDIR, YDCPG_GPAR%SWDIF, PRDG_MU0LU, ZALBD1, ZFRSOLU, PCLDROP,                                     &
    & YSPP_RSWINHF=YSPP_ALL%YSPP_RSWINHF, YSPP_RLWINHF=YSPP_ALL%YSPP_RLWINHF)

  ELSE

    IF (LDMSE) THEN
      DO JSW=1, YDMODEL%YRML_PHY_RAD%YRERAD%NSW
        ZTRSODIR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JSW) = YDCPG_GPAR%SWDIR(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JSW)
        ZTRSODIF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JSW) = YDCPG_GPAR%SWDIF(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JSW)
      ENDDO
    ENDIF
    ZCTRSO(:,:) = 0._JPRB

  ENDIF

  DO JLEV=1,YDCPG_OPTS%KFLEVG
    ZTENT(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA, JLEV) = 0.0_JPRB
  ENDDO

  ZSUDU(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA)=0.0_JPRB

  CALL RADHEAT(YDMODEL%YRCST, YDMODEL%YRML_PHY_EC%YRTHF, YDMODEL%YRML_PHY_RAD%YRERAD,                 &
  & YDMODEL%YRML_PHY_RAD%YRERDI, YDMODEL%YRML_PHY_MF,                                                 &
  & YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA, YDCPG_OPTS%KLON,                                              &
  & YDCPG_OPTS%KFLEVG, YDMF_PHYS_BASE_STATE%YCPG_PHY%PRE, PEMIS, YDMF_PHYS%RAD%EMTD,                  &
  & PRDG_MU0, PRDG_SOLO, PQVM,                                                                        &
  & ZTENT, YDMF_PHYS%RAD%TRSW, ZTRSOD, PTSURF, YDCPG_OPTS%ZDTPHY, ZTRSODIR, ZTRSODIF, PALBD, PALBP,   &
  & YDMF_PHYS%OUT%FRSO(:,:,1), YDMF_PHYS%OUT%FRTH(:,:,1), YDMF_PHYS%OUT%FRSODS, YDMF_PHYS%OUT%FRTHDS, &
  & ZCEMTR, ZCTRSO, YDMF_PHYS%OUT%FRSOC, YDMF_PHYS%OUT%FRTHC,                                         &
  & ZSUDU, ZSDUR, ZDSRP, PZS_FSWDIR, PZS_FSWDIF, YDMF_PHYS%OUT%FRSOPS, ZFRSOFS, YDMF_PHYS%OUT%FRSOPT)

  ! update temperature tendency by radiative contribution
  DO JLEV=1,YDCPG_OPTS%KFLEVG
    DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
      PTENDT(JLON,JLEV) = PTENDT(JLON,JLEV) + ZTENT(JLON,JLEV)
    ENDDO
  ENDDO

  !initialisation de ZZI_THRAD
  IF (YDMODEL%YRML_PHY_MF%YRPARAR%CMICRO == 'LIMA') THEN
    DO JLEV = 1, YDCPG_OPTS%KFLEVG
      DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
        PDTHRAD(JLON,JLEV)=ZTENT(JLON,JLEV)/PEXNREFM(JLON,JLEV)
      ENDDO
      PP1EZDIAG(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JLEV) = PDTHRAD(YDCPG_BNDS%KIDIA:YDCPG_BNDS%KFDIA,JLEV)
    ENDDO
  ENDIF

  DO JLON = YDCPG_BNDS%KIDIA, YDCPG_BNDS%KFDIA
    ! update sunshine duration [s]
    YDMF_PHYS_SURF%GSD_VD%PSUND(JLON) = YDMF_PHYS_SURF%GSD_VD%PSUND(JLON) + ZSDUR(JLON)*PADTMS ! fix stepx case
    ! Estimate of the direct normal irradiance, with securities
    IF (PRDG_MU0(JLON) > 3.0E-02_JPRB) THEN
      YDMF_PHYS%OUT%FRSDNI(JLON) = MAX(0.0_JPRB,YDMF_PHYS%OUT%FRSOPS(JLON)/PRDG_MU0(JLON))
    ELSE
      YDMF_PHYS%OUT%FRSDNI(JLON) = MAX(0.0_JPRB,YDMF_PHYS%OUT%FRSOPS(JLON))
    ENDIF
  ENDDO

  IF (YDMODEL%YRML_DIAG%YRLDDH%LFLEXDIA) THEN
    CALL NEW_ADD_FIELD_3D(YDMODEL%YRML_DIAG%YRMDDH, YDMF_PHYS%OUT%FRSO(:, :, 1), 'FCTRAYSO', YDDDH)
    CALL NEW_ADD_FIELD_3D(YDMODEL%YRML_DIAG%YRMDDH, YDMF_PHYS%OUT%FRTH(:, :, 1), 'FCTRAYTH', YDDDH)
  ENDIF

  IF (LHOOK) CALL DR_HOOK('APL_AROME_RADIATION_MOD:APL_AROME_RADIATION', 1, ZHOOK_HANDLE)

END SUBROUTINE APL_AROME_RADIATION
